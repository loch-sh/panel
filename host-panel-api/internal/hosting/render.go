// RenderConfig holds the installation-wide settings used to render stacks.
type RenderConfig struct {
	SitesDir        string // absolute, identical on the host and in the API container
	TraefikNetwork  string
	HTTPEntrypoint  string
	HTTPSEntrypoint string
	CertResolver    string // optional
	// Networks resolves the panel networks (internal/networks).
	Networks NetworkResolver
}

// NetworkResolver gives the Docker networks of the panel.
type NetworkResolver = networks.Resolver

// File names inside a stack directory.
const (
	ComposeFile   = composekit.DefaultComposeFile
	ConfigDir     = "config"
	PHPIniFile    = "php.ini"
	VhostFile     = "vhost.conf"
	webService    = "web"
	appMountPoint = "/app"
)

// Mount points of the snippets in the webdevops images. The php.ini snippet
// sorts last in conf.d so it overrides the settings derived from the form.
const (
	phpIniTarget      = "/usr/local/etc/php/conf.d/zz-loch.ini"
	nginxVhostTarget  = "/opt/docker/etc/nginx/vhost.common.d/99-loch.conf"
	apacheVhostTarget = "/opt/docker/etc/httpd/vhost.common.d/99-loch.conf"
)

// composeHeader documents how to boot the stack without the panel: its
// private networks are plain Docker networks, created once per host.
func composeHeader(nets []networks.Ref) string {
	var b strings.Builder
	b.WriteString("# Generated by Loch.sh Panel (hosting). Boot without the panel with:\n")
	b.WriteString(networks.BootComments(nets))
	b.WriteString("#   docker compose up -d\n")
	b.WriteString("# The x-loch section holds the panel settings. Manual edits are detected and\n")
	b.WriteString("# block updates from the panel until they are overwritten.\n")
	return b.String()
}

type composeFile struct {
	Name     string                    `yaml:"name"`
	XLoch    *Spec                     `yaml:"x-loch"`
	Services map[string]composeService `yaml:"services"`
	Networks map[string]composeNetwork `yaml:"networks"`
}

type composeService struct {
	Image       string            `yaml:"image"`
	Restart     string            `yaml:"restart"`
	Init        bool              `yaml:"init"`
	TTY         bool              `yaml:"tty"`
	StdinOpen   bool              `yaml:"stdin_open"`
	Environment map[string]string `yaml:"environment,omitempty"`
	Volumes     []composeVolume   `yaml:"volumes"`
	Networks    []string          `yaml:"networks"`
	MemLimit    string            `yaml:"mem_limit,omitempty"`
	CPUs        string            `yaml:"cpus,omitempty"`
	PidsLimit   int               `yaml:"pids_limit"`
	SecurityOpt []string          `yaml:"security_opt"`
	CapDrop     []string          `yaml:"cap_drop,omitempty"`
	Logging     composeLogging    `yaml:"logging"`
	Labels      map[string]string `yaml:"labels"`
}

// composeVolume is a bind mount in long syntax: unlike "src:dst:ro", no
// character of the paths can be mistaken for a separator.
type composeVolume struct {
	Type     string `yaml:"type"`
	Source   string `yaml:"source"`
	Target   string `yaml:"target"`
	ReadOnly bool   `yaml:"read_only,omitempty"`
	Bind     struct {
		CreateHostPath bool `yaml:"create_host_path"`
	} `yaml:"bind"`
}

func bindMount(source, target string, readOnly bool) composeVolume {
	// create_host_path: false: a missing source is an error instead of an
	// empty directory created by the daemon as root.
	return composeVolume{Type: "bind", Source: source, Target: target, ReadOnly: readOnly}
}

type composeLogging struct {
	Driver  string            `yaml:"driver"`
	Options map[string]string `yaml:"options"`
}

type composeNetwork struct {
	Name     string `yaml:"name"`
	External bool   `yaml:"external"`
}

// Render generates the compose file of a validated spec. The output is
// deterministic, so re-rendering the embedded spec and comparing bytes
// detects manual edits.
func Render(spec *Spec, cfg RenderConfig) ([]byte, error) {
	s := *spec
	s.Version = SpecVersion

	// Compose interpolates "$" everywhere, extension fields included: the
	// embedded copy of the env values is escaped too (see ParseSpec).
	stored := s
	stored.Env = make([]EnvVar, len(s.Env))
	for i, v := range s.Env {
		stored.Env[i] = EnvVar{Name: v.Name, Value: escapeCompose(v.Value)}
	}

	service := composeService{
		Image:   Image(&s),
		Restart: "unless-stopped",
		// init: an init process reaps zombies and forwards signals;
		// tty + stdin_open: interactive container, like `docker run -it`.
		Init:        true,
		TTY:         true,
		StdinOpen:   true,
		Environment: environment(&s),
		Volumes:     volumes(&s, cfg),
		Networks:    []string{"traefik"},
		PidsLimit:   512,
		SecurityOpt: []string{"no-new-privileges:true"},
		Logging: composeLogging{
			Driver:  "json-file",
			Options: map[string]string{"max-size": "10m", "max-file": "3"},
		},
		Labels: labels(&s, cfg),
	}

	// Limits are only written when set (0 = unlimited).
	if s.Resources.MemoryMB > 0 {
		service.MemLimit = fmt.Sprintf("%dm", s.Resources.MemoryMB)
	}
	if s.Resources.CPUs > 0 {
		service.CPUs = strconv.FormatFloat(s.Resources.CPUs, 'f', -1, 64)
	}

	doc := composeFile{
		Name:     ProjectName(s.Name),
		XLoch:    &stored,
		Services: map[string]composeService{webService: service},
		Networks: map[string]composeNetwork{
			"traefik": {Name: cfg.TraefikNetwork, External: true},
		},
	}
	refs, err := resolveNetworks(s.Networks, cfg.Networks)
	if err != nil {
		return nil, err
	}
	if len(refs) > 0 {
		web := doc.Services[webService]
		for _, n := range refs {
			web.Networks = append(web.Networks, n.Name)
			doc.Networks[n.Name] = composeNetwork{Name: n.DockerName, External: true}
		}
		// Panel networks are shared with other sites and instances: no raw
		// sockets (ARP spoofing would let a site read the traffic, and the
		// passwords, of the others on a network without TLS).
		web.CapDrop = []string{"NET_RAW"}
		doc.Services[webService] = web
	}

	var buf bytes.Buffer
	buf.WriteString(composeHeader(refs))
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// resolveNetworks returns the references of the networks of a stack (sorted
// by Normalize, checked by Validate).
func resolveNetworks(names []string, r NetworkResolver) ([]networks.Ref, error) {
	if len(names) == 0 {
		return nil, nil
	}
	if r == nil {
		return nil, errors.New("no network registry")
	}
	out := make([]networks.Ref, 0, len(names))
	for _, name := range names {
		ref, ok := r.Lookup(name)
		if !ok {
			return nil, newError(CodeInvalidNetwork, "networks", "unknown network %q", name)
		}
		out = append(out, ref)
	}
	return out, nil
}

// ParseSpec extracts the x-loch spec of a compose file. It returns nil when
// the file is not a hosted stack generated by the panel.
func ParseSpec(data []byte) (*Spec, error) {
	var doc struct {
		Name  string `yaml:"name"`
		XLoch *Spec  `yaml:"x-loch"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, err
	}
	if doc.XLoch == nil || doc.Name != ProjectName(doc.XLoch.Name) {
		return nil, nil
	}
	for i, v := range doc.XLoch.Env {
		doc.XLoch.Env[i].Value = strings.ReplaceAll(v.Value, "$$", "$")
	}
	return doc.XLoch, nil
}

// escapeCompose escapes "$" so Docker Compose does not interpolate values.
func escapeCompose(v string) string { return composekit.EscapeInterpolation(v) }

func environment(s *Spec) map[string]string {
	env := make(map[string]string, len(s.Env)+8)
	for _, v := range s.Env {
		env[v.Name] = escapeCompose(v.Value)
	}
	env["WEB_DOCUMENT_ROOT"] = path.Join(appMountPoint, s.DocumentRoot)
	if s.PHP != nil {
		env["PHP_MEMORY_LIMIT"] = s.PHP.MemoryLimit
		env["PHP_UPLOAD_MAX_FILESIZE"] = s.PHP.UploadMaxFilesize
		env["PHP_POST_MAX_SIZE"] = s.PHP.PostMaxSize
		env["PHP_MAX_EXECUTION_TIME"] = strconv.Itoa(s.PHP.MaxExecutionTime)
		env["PHP_DATE_TIMEZONE"] = s.PHP.Timezone
		env["WEB_PHP_TIMEOUT"] = strconv.Itoa(webPHPTimeout(s))
		if len(s.PHP.DisabledModules) > 0 {
			env["PHP_DISMOD"] = strings.Join(s.PHP.DisabledModules, ",")
		}
		env["PHP_DISPLAY_ERRORS"] = "0"
		if s.PHP.DisplayErrors {
			env["PHP_DISPLAY_ERRORS"] = "1"
		}
	}
	return env
}

func volumes(s *Spec, cfg RenderConfig) []composeVolume {
	vols := []composeVolume{bindMount(path.Join(cfg.SitesDir, s.Site), appMountPoint, false)}
	if s.Template.HasPHP() {
		vols = append(vols, bindMount("./"+ConfigDir+"/"+PHPIniFile, phpIniTarget, true))
	}
	vhostTarget := apacheVhostTarget
	if s.Template.UsesNginx() {
		vhostTarget = nginxVhostTarget
	}
	vols = append(vols, bindMount("./"+ConfigDir+"/"+VhostFile, vhostTarget, true))
	if s.Routing != RoutingDefault {
		vols = append(vols, bindMount("./"+ConfigDir+"/"+RoutingFile, routingTarget(s.Template), true))
	}
	if hasFPMPool(s) {
		vols = append(vols, bindMount("./"+ConfigDir+"/"+FPMPoolFile, fpmPoolTarget, true))
	}
	return vols
}

func labels(s *Spec, cfg RenderConfig) map[string]string {
	project := ProjectName(s.Name)
	l := map[string]string{
		"sh.loch.managed": "true",
		"sh.loch.hosting": s.Name,
	}
	if len(s.Domains) == 0 {
		l["traefik.enable"] = "false"
		return l
	}

	hosts := make([]string, len(s.Domains))
	for i, d := range s.Domains {
		hosts[i] = "Host(`" + d + "`)"
	}
	rule := strings.Join(hosts, " || ")
	router := "traefik.http.routers." + project

	l["traefik.enable"] = "true"
	l["traefik.docker.network"] = cfg.TraefikNetwork
	l["traefik.http.services."+project+".loadbalancer.server.port"] = "80"

	l[router+"-http.rule"] = rule
	l[router+"-http.entrypoints"] = cfg.HTTPEntrypoint
	l[router+"-http.service"] = project
	if s.RedirectHTTPS {
		middleware := project + "-redirect"
		l[router+"-http.middlewares"] = middleware
		l["traefik.http.middlewares."+middleware+".redirectscheme.scheme"] = "https"
		l["traefik.http.middlewares."+middleware+".redirectscheme.permanent"] = "true"
	}

	if s.HTTPS {
		l[router+"-https.rule"] = rule
		l[router+"-https.entrypoints"] = cfg.HTTPSEntrypoint
		l[router+"-https.service"] = project
		l[router+"-https.tls"] = "true"
		if cfg.CertResolver != "" {
			l[router+"-https.tls.certresolver"] = cfg.CertResolver
		}
	}
	return l
}
