package hosting

// Reading stacks: loading and validating them from disk, listing, details,
// sites and PHP modules.

import (
	"bytes"
	"context"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/moby/moby/api/types/container"
)

// StackSummary is a stack as shown in lists.
type StackSummary struct {
	Name          string     `json:"name"`
	Template      Template   `json:"template"`
	PHPVersion    string     `json:"phpVersion,omitempty"`
	Image         string     `json:"image"`
	Site          string     `json:"site"`
	Domains       []string   `json:"domains"`
	HTTPS         bool       `json:"https"`
	RedirectHTTPS bool       `json:"redirectHttps"`
	Project       string     `json:"project"` // compose project, for the generic stack actions
	Status        string     `json:"status"`  // running | partial | stopped | not_deployed
	Running       int        `json:"running"`
	Total         int        `json:"total"`
	Modified      bool       `json:"modified"` // compose edited outside the panel
	Operation     *Operation `json:"operation,omitempty"`
}

// ContainerInfo is a container of a stack.
type ContainerInfo struct {
	ID     string `json:"id"`
	Name   string `json:"name"`
	State  string `json:"state"`
	Status string `json:"status"`
	Image  string `json:"image"`
}

// StackDetail is a stack with its full settings.
type StackDetail struct {
	StackSummary
	Spec       *Spec           `json:"spec"`
	Snippets   Snippets        `json:"snippets"`
	Containers []ContainerInfo `json:"containers"`
	// Compose is the compose.yaml on disk, as `docker compose` runs it.
	Compose string `json:"compose"`
	// RoutingFile is the routing file in use (generated or custom), "" for
	// the image default.
	RoutingFile string `json:"routingFile"`
}

// SiteInfo is a directory of the sites directory.
type SiteInfo struct {
	Name  string `json:"name"`
	Stack string `json:"stack,omitempty"` // stack using it, if any
}

type loadedStack struct {
	spec     *Spec
	modified bool
	dir      string
}

func (m *Manager) stackDir(name string) string {
	return filepath.Join(m.cfg.StacksDir, ProjectName(name))
}

// load reads a managed stack. It returns a CodeStackNotFound error when the
// directory does not exist or does not hold a compose file generated by the
// panel for this name.
func (m *Manager) load(name string) (*loadedStack, error) {
	if ValidateName(name) != nil {
		return nil, notFound()
	}
	dir := m.stackDir(name)
	if err := realDir(dir); err != nil {
		return nil, notFound()
	}
	data, err := readFileNoFollow(filepath.Join(dir, ComposeFile))
	if err != nil {
		return nil, notFound()
	}
	spec, err := ParseSpec(data)
	if err != nil || spec == nil || spec.Name != name {
		return nil, notFound()
	}
	// Only directories created by the panel are managed, and their x-loch
	// section is re-validated: the stacks directory is shared with CI, so a
	// compose file found there is untrusted input (its site is used for
	// deletions, for instance).
	if !isRegularFile(filepath.Join(dir, ManagedMarker)) {
		return nil, notFound()
	}
	if err := validateStored(spec); err != nil {
		m.logger.Warn("hosting: ignoring stack with an invalid x-loch section", "stack", name, "error", err.Message)
		return nil, notFound()
	}
	rendered, err := Render(spec, m.cfg.Render)
	// A stack written by an older panel version renders differently without
	// having been edited by hand: only compare files of the current version.
	modified := err != nil || (!bytes.Equal(rendered, stripStamp(data)) && spec.Version == SpecVersion)
	// The generated Symfony rules are part of what the panel writes: a hand
	// edit is reported like a compose edit. (Custom rules are the source
	// themselves; a missing file is regenerated on deploy.)
	if !modified && spec.Version == SpecVersion {
		modified = generatedFilesEdited(dir, spec)
	}
	return &loadedStack{spec: spec, modified: modified, dir: dir}, nil
}

// generatedFilesEdited reports whether a file the panel generates (Symfony
// routing rules, PHP-FPM pool) differs from what it would write. Custom rules
// are user content, and a missing file is regenerated on deploy.
func generatedFilesEdited(dir string, spec *Spec) bool {
	gen := generatedFor(spec, Snippets{})
	differs := func(name, want string) bool {
		current, err := readFileNoFollow(filepath.Join(dir, ConfigDir, name))
		return err == nil && string(current) != want
	}
	if isGeneratedRouting(spec.Routing) && differs(RoutingFile, gen.Routing) {
		return true
	}
	return hasFPMPool(spec) && differs(FPMPoolFile, gen.FPMPool)
}

func notFound() *Error {
	return &Error{Code: CodeStackNotFound, Message: "hosted stack not found"}
}

func storageError(err error) *Error {
	return &Error{Code: CodeStorage, Message: "storage error: " + err.Error()}
}

// loadAll returns every managed stack, keyed by name.
func (m *Manager) loadAll() (map[string]*loadedStack, error) {
	entries, err := os.ReadDir(m.cfg.StacksDir)
	if err != nil {
		return nil, err
	}
	stacks := make(map[string]*loadedStack)
	for _, e := range entries {
		name, ok := strings.CutPrefix(e.Name(), StackPrefix)
		if !ok || !e.IsDir() || e.Type()&os.ModeSymlink != 0 {
			continue
		}
		if s, err := m.load(name); err == nil {
			stacks[name] = s
		}
	}
	return stacks, nil
}

// List returns every hosted stack with its runtime status.
func (m *Manager) List(ctx context.Context) ([]StackSummary, error) {
	stacks, err := m.loadAll()
	if err != nil {
		return nil, storageError(err)
	}
	containers, err := m.docker.ListContainers(ctx)
	if err != nil {
		return nil, err
	}
	byProject := groupByProject(containers)

	out := make([]StackSummary, 0, len(stacks))
	for name, s := range stacks {
		out = append(out, m.summary(name, s, byProject[ProjectName(name)]))
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// Get returns a stack with its settings, snippets and containers.
func (m *Manager) Get(ctx context.Context, name string) (*StackDetail, error) {
	s, err := m.load(name)
	if err != nil {
		return nil, err
	}
	containers, err := m.docker.ListContainers(ctx)
	if err != nil {
		return nil, err
	}
	own := groupByProject(containers)[ProjectName(name)]

	compose, err := readFileNoFollow(filepath.Join(s.dir, ComposeFile))
	if err != nil {
		return nil, storageError(err)
	}
	snippets, routing, err := readSnippets(s)
	if err != nil {
		return nil, err
	}

	infos := make([]ContainerInfo, 0, len(own))
	for _, c := range own {
		infos = append(infos, ContainerInfo{
			ID: c.ID, Name: containerName(c), State: string(c.State), Status: c.Status, Image: c.Image,
		})
	}
	summary := m.summary(name, s, own)
	summary.Operation = m.Operation(name)
	return &StackDetail{
		StackSummary: summary,
		Spec:         s.spec,
		Snippets:     snippets,
		RoutingFile:  routing,
		Containers:   infos,
		Compose:      string(compose),
	}, nil
}

func (m *Manager) summary(name string, s *loadedStack, containers []container.Summary) StackSummary {
	running := 0
	for _, c := range containers {
		if c.State == container.StateRunning {
			running++
		}
	}
	status := "not_deployed"
	switch {
	case len(containers) == 0:
	case running == len(containers):
		status = "running"
	case running > 0:
		status = "partial"
	default:
		status = "stopped"
	}
	return StackSummary{
		Name: name, Template: s.spec.Template, PHPVersion: s.spec.PHPVersion,
		Image: Image(s.spec), Site: s.spec.Site, Domains: s.spec.Domains,
		HTTPS: s.spec.HTTPS, RedirectHTTPS: s.spec.RedirectHTTPS,
		Project: ProjectName(name), Status: status,
		Running: running, Total: len(containers),
		Modified: s.modified, Operation: withoutOutput(m.Operation(name)),
	}
}

// withoutOutput drops the compose output (up to 32 KB) from list results;
// it is only returned with the stack details.
func withoutOutput(op *Operation) *Operation {
	if op != nil {
		op.Output = ""
	}
	return op
}

// readSnippets reads the snippets of a stack and its routing file in use
// ("" for the image default routing, even if a file was left behind).
func readSnippets(s *loadedStack) (Snippets, string, error) {
	read := func(name string) (string, error) {
		return readOptional(filepath.Join(s.dir, ConfigDir, name))
	}
	var snippets Snippets
	var routing string
	var err error
	if snippets.PHPIni, err = read(PHPIniFile); err != nil {
		return Snippets{}, "", storageError(err)
	}
	if snippets.Vhost, err = read(VhostFile); err != nil {
		return Snippets{}, "", storageError(err)
	}
	if routing, err = read(RoutingFile); err != nil {
		return Snippets{}, "", storageError(err)
	}
	switch s.spec.Routing {
	case RoutingDefault:
		routing = ""
	case RoutingCustom:
		snippets.RoutingRules = routing
	}
	return snippets, routing, nil
}

// Sites lists the directories of the sites directory and the stack using each.
func (m *Manager) Sites() ([]SiteInfo, error) {
	dirs, err := listSiteDirs(m.cfg.Render.SitesDir)
	if err != nil {
		return nil, storageError(err)
	}
	stacks, err := m.loadAll()
	if err != nil {
		return nil, storageError(err)
	}
	usedBy := make(map[string]string, len(stacks))
	for name, s := range stacks {
		usedBy[s.spec.Site] = name
	}
	out := make([]SiteInfo, 0, len(dirs))
	for _, d := range dirs {
		out = append(out, SiteInfo{Name: d, Stack: usedBy[d]})
	}
	return out, nil
}

// PHPModules lists the PHP modules that can be disabled in the image of a
// PHP template and version (the image is pulled on first use).
func (m *Manager) PHPModules(ctx context.Context, template Template, version string) ([]PHPModule, error) {
	if !template.HasPHP() {
		return nil, newError(CodeInvalidTemplate, "template", "template %q has no PHP", template)
	}
	if !validPHPVersion(version) {
		return nil, newError(CodeInvalidPHPVersion, "phpVersion", "unsupported PHP version %q", version)
	}
	files, err := m.modules.ConfFiles(ctx, Image(&Spec{Template: template, PHPVersion: version}))
	if err != nil {
		m.logger.Error("hosting: cannot inspect image", "error", err)
		return nil, &Error{Code: CodeImageInspect, Message: "cannot inspect the PHP image"}
	}
	return ModulesFromFiles(files), nil
}

// checkModules validates the disabled PHP modules against the image.
func (m *Manager) checkModules(ctx context.Context, spec *Spec) error {
	if spec.PHP == nil || len(spec.PHP.DisabledModules) == 0 {
		return nil
	}
	files, err := m.modules.ConfFiles(ctx, Image(spec))
	if err != nil {
		m.logger.Error("hosting: cannot inspect image", "error", err)
		return &Error{Code: CodeImageInspect, Message: "cannot inspect the PHP image"}
	}
	if err := checkDisabledModules(files, spec.PHP.DisabledModules); err != nil {
		return err
	}
	return nil
}
