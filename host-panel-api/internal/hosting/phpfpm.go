package hosting

// PHP limits per context.
//
// The webdevops images run web requests through PHP-FPM (behind Nginx or
// Apache) and crons/console commands through the PHP CLI. Both read php.ini
// (PHP_* variables), but:
//   - a PHP-FPM pool file can override php.ini for web requests only
//     (php_admin_value, which the application cannot change with ini_set);
//   - the PHP CLI always ignores max_execution_time (it is unlimited there).
//
// So memory_limit applies to the CLI and is the default for the web,
// webMemoryLimit optionally overrides it for web requests, and
// max_execution_time only concerns the web.

import (
	"fmt"
	"strings"
)

// FPMPoolFile holds the PHP-FPM pool overrides of a stack.
const FPMPoolFile = "php-fpm.conf"

// fpmPoolTarget is included by php-fpm.conf of the images after the
// image's own pool files: re-opening the [www] pool overrides its values.
const fpmPoolTarget = "/usr/local/etc/php-fpm.d/zz-loch.conf"

// defaultWebPHPTimeout is the web server timeout of the images (seconds).
const defaultWebPHPTimeout = 600

// hasFPMPool reports whether a stack needs the PHP-FPM pool file.
func hasFPMPool(spec *Spec) bool {
	return spec.PHP != nil && spec.PHP.WebMemoryLimit != ""
}

// FPMPoolContent returns the PHP-FPM pool overrides of a stack ("" when
// none).
func FPMPoolContent(spec *Spec) string {
	if !hasFPMPool(spec) {
		return ""
	}
	var b strings.Builder
	b.WriteString("; Generated by Loch.sh Panel: PHP limits of web requests (the CLI uses php.ini).\n")
	b.WriteString("[www]\n")
	fmt.Fprintf(&b, "php_admin_value[memory_limit] = %s\n", spec.PHP.WebMemoryLimit)
	return b.String()
}

// webPHPTimeout is how long Nginx/Apache wait for PHP-FPM (WEB_PHP_TIMEOUT):
// never shorter than the image default, and longer than max_execution_time
// so the web server does not cut a request PHP would still run.
// max_execution_time 0 (unlimited) gets the largest allowed value.
func webPHPTimeout(spec *Spec) int {
	limit := maxExecutionTime
	if spec.PHP != nil && spec.PHP.MaxExecutionTime > 0 {
		limit = spec.PHP.MaxExecutionTime
	}
	return max(defaultWebPHPTimeout, limit+30)
}
