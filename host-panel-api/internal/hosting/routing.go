package hosting

import (
	"strings"
)

// Routing modes of the web server (Spec.Routing).
const (
	RoutingDefault = ""        // routing of the webdevops image
	RoutingSymfony = "symfony" // Symfony front controller rules generated by the panel
	RoutingLaravel = "laravel" // Laravel front controller rules generated by the panel
	RoutingCustom  = "custom"  // rules written by the user (Snippets.RoutingRules)
)

// isGeneratedRouting reports whether the panel generates the routing file
// (framework presets), as opposed to the image default or custom rules.
func isGeneratedRouting(r string) bool {
	return r == RoutingSymfony || r == RoutingLaravel
}

// RoutingFile holds the routing rules of a stack (config/routing.conf).
const RoutingFile = "routing.conf"

// Where the routing file is mounted. For Nginx it replaces the image's
// location / file, which is included before the PHP location: its regex
// locations take precedence, and location / can be redefined. For Apache it
// is included first in the VirtualHost (PHP is configured globally).
const (
	nginxRoutingTarget  = "/opt/docker/etc/nginx/vhost.common.d/10-location-root.conf"
	apacheRoutingTarget = "/opt/docker/etc/httpd/vhost.common.d/05-loch-routing.conf"
)

// DefaultAssetDirs are served without falling back to the front controller
// in the Symfony mode (missing files return a 404 instead of Symfony's page).
var DefaultAssetDirs = []string{"bundles"}

const maxAssetDirs = 20

func validRouting(r string) bool {
	return r == RoutingDefault || r == RoutingCustom || isGeneratedRouting(r)
}

// validateRouting checks the routing mode, the asset directories and the
// custom rules of a spec.
func validateRouting(spec *Spec, snippets Snippets) *Error {
	if !validRouting(spec.Routing) {
		return newError(CodeInvalidRouting, "routing", "unknown routing %q", spec.Routing)
	}
	if isGeneratedRouting(spec.Routing) && !spec.Template.HasPHP() {
		return newError(CodeInvalidRouting, "routing", "the %s routing requires a PHP template", spec.Routing)
	}
	if spec.Routing != RoutingSymfony && len(spec.AssetDirs) > 0 {
		return newError(CodeInvalidRouting, "assetDirs", "asset directories only apply to the Symfony routing")
	}
	if len(spec.AssetDirs) > maxAssetDirs {
		return newError(CodeInvalidRouting, "assetDirs", "at most %d asset directories", maxAssetDirs)
	}
	for i, d := range spec.AssetDirs {
		if d == "" || !validWebPath(d) || containsString(spec.AssetDirs[:i], d) {
			return newError(CodeInvalidRouting, "assetDirs", "invalid or duplicate asset directory %q", d)
		}
	}
	if spec.Routing != RoutingCustom && snippets.RoutingRules != "" {
		return newError(CodeInvalidRouting, "routingRules", "routing rules only apply to the custom routing")
	}
	return nil
}

// validateCustomRules checks that the custom routing has rules: an empty
// file would replace the image's location / with nothing (Nginx).
func validateCustomRules(spec *Spec, snippets Snippets) *Error {
	if spec.Routing == RoutingCustom && strings.TrimSpace(snippets.RoutingRules) == "" {
		return newError(CodeInvalidRouting, "routingRules", "the custom routing needs rules")
	}
	return nil
}

func containsString(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// routingTarget returns where the routing file is mounted for a template.
func routingTarget(t Template) string {
	if t.UsesNginx() {
		return nginxRoutingTarget
	}
	return apacheRoutingTarget
}

// RoutingContent returns the content of the routing file of a stack: the
// generated framework rules, the custom rules, or "" for the image default.
func RoutingContent(spec *Spec, snippets Snippets) string {
	switch spec.Routing {
	case RoutingSymfony:
		return SymfonyRules(spec.Template, spec.DocumentRoot, spec.AssetDirs, webPHPTimeout(spec))
	case RoutingLaravel:
		return LaravelRules(spec.Template, spec.DocumentRoot, webPHPTimeout(spec))
	case RoutingCustom:
		return snippets.RoutingRules
	}
	return ""
}

// PreviewRules validates the routing inputs of a spec whose Routing is a
// framework preset (symfony or laravel) and returns the rules generated for
// it, as a starting point for custom rules.
func PreviewRules(spec *Spec) (string, error) {
	if !isGeneratedRouting(spec.Routing) {
		return "", newError(CodeInvalidRouting, "routing", "unknown framework %q: expected symfony or laravel", spec.Routing)
	}
	Normalize(spec)
	if !spec.Template.Valid() {
		return "", newError(CodeInvalidTemplate, "template", "unknown template %q", spec.Template)
	}
	if !validWebPath(spec.DocumentRoot) {
		return "", newError(CodeInvalidDocRoot, "documentRoot", "invalid document root")
	}
	if spec.PHP != nil && (spec.PHP.MaxExecutionTime < 0 || spec.PHP.MaxExecutionTime > maxExecutionTime) {
		return "", newError(CodeInvalidPHPSetting, "php.maxExecutionTime", "max_execution_time must be 0-%d seconds", maxExecutionTime)
	}
	if err := validateRouting(spec, Snippets{}); err != nil {
		return "", err
	}
	return RoutingContent(spec, Snippets{}), nil
}
