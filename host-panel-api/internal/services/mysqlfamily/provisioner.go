package mysqlfamily

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"host-panel-api/internal/services"
)

type provisioner struct{ e *Engine }

func (p provisioner) dialect(v string) dialect { return dialectFor(p.e.flavor, v) }

// reserved are the system schemas and accounts of MariaDB and MySQL.
var reserved = services.ReservedNames(
	[]string{"mysql", "sys", "information_schema", "performance_schema"},
	[]string{"mariadb", "mysql", "sys_"},
)

// ValidateName refuses the system names and applies the length limit of
// the version (MySQL 5.6 user names: 16 characters).
func (p provisioner) ValidateName(v services.Version, name string) *services.Error {
	if len(name) > v.NameLimit() {
		return services.NameTooLong(v.NameLimit())
	}
	return reserved(name)
}

func (p provisioner) Init(ctx context.Context, t services.Target) error {
	_, err := p.dialect(t.Version.Version).run(ctx, t, "init", initSQL)
	return err
}

func (p provisioner) List(ctx context.Context, t services.Target) ([]services.Resource, error) {
	out, err := p.dialect(t.Version.Version).run(ctx, t, "list", listSQL)
	if err != nil {
		return nil, err
	}
	return parseList(out)
}

func checkPassword(password string) error {
	if !services.IsGeneratedPassword(password) {
		return errors.New("mysqlfamily: refusing a password that was not generated by the panel")
	}
	return nil
}

// Provision creates the user, then the database (with its grant and the
// panel record). A failure of the second step is known to come after the
// user was created by this call: only then is the user dropped again. An
// unknown outcome of the second step is resolved by replaying it (every
// statement is idempotent).
func (p provisioner) Provision(ctx context.Context, t services.Target, name, password string) error {
	return p.provision(ctx, t, name, password, false)
}

// LegacyAuth: MySQL 8.4 to 8.x only (MariaDB and MySQL 5.6 already use
// mysql_native_password; MySQL 9 no longer has it).
func (p provisioner) LegacyAuth(v services.Version) bool {
	return p.dialect(v.Version).nativePlugin
}

// ProvisionLegacy creates the user with mysql_native_password, for clients
// without caching_sha2_password over a plain connection (no TLS, no RSA key
// exchange).
func (p provisioner) ProvisionLegacy(ctx context.Context, t services.Target, name, password string) error {
	if !p.LegacyAuth(t.Version) {
		return errors.New("mysqlfamily: no legacy authentication on this version")
	}
	return p.provision(ctx, t, name, password, true)
}

func (p provisioner) provision(ctx context.Context, t services.Target, name, password string, native bool) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	d := p.dialect(t.Version.Version)
	if _, err := d.run(ctx, t, "create user", d.createUserSQL(name, password, native)); err != nil {
		var ee *services.EngineError
		if errors.As(err, &ee) && ee.Detail == "error 1396" { // the user exists
			return fmt.Errorf("%w (user)", services.ErrResourceExists)
		}
		return err
	}
	_, err := d.run(ctx, t, "create database", d.createDatabaseSQL(name, false))
	if errors.Is(err, services.ErrOutcomeUnknown) {
		if _, rerr := d.run(context.WithoutCancel(ctx), t, "create database", d.createDatabaseSQL(name, true)); rerr == nil {
			return nil
		}
		return err
	}
	if err != nil {
		// Drop what this call created: the user always, the database only
		// when it did not exist before (1007 means it did).
		cleanup := d.dropUserSQL(name, true)
		if !errors.Is(err, services.ErrResourceExists) {
			cleanup = fmt.Sprintf("DROP DATABASE IF EXISTS %s;\n", quoteIdent(name)) + cleanup
		}
		if _, derr := d.run(context.WithoutCancel(ctx), t, "drop user", cleanup); derr != nil {
			return fmt.Errorf("%w (and dropping the new user failed: %v)", err, derr)
		}
		return err
	}
	return nil
}

// Deprovision drops the user, closes its sessions (DROP USER does not end
// them, and an open transaction would hold the metadata locks DROP DATABASE
// waits for), then drops the database and its record. A failure after the
// user was dropped leaves an unmanaged database, listed, and the deletion
// can be retried: every step is idempotent.
func (p provisioner) Deprovision(ctx context.Context, t services.Target, name string) error {
	d := p.dialect(t.Version.Version)
	exists := true
	if d.legacy {
		out, err := d.run(ctx, t, "user exists", userExistsSQL(name))
		if err != nil {
			return err
		}
		exists = strings.TrimSpace(string(out)) != "0"
	}
	if stmt := d.dropUserSQL(name, exists); stmt != "" {
		if _, err := d.run(ctx, t, "drop user", stmt); err != nil {
			return err
		}
	}
	d.killSessions(ctx, t, name)
	_, err := d.run(ctx, t, "drop database", dropDatabaseSQL(name))
	return err
}

// SetPassword changes the password and closes the sessions opened with the
// old one.
func (p provisioner) SetPassword(ctx context.Context, t services.Target, name, password string) error {
	if err := checkPassword(password); err != nil {
		return err
	}
	d := p.dialect(t.Version.Version)
	// The user keeps its mechanism (legacy or not).
	native := false
	if d.plainAuth {
		out, err := d.run(ctx, t, "auth plugin", nativeUserSQL(name))
		if err != nil {
			return err
		}
		native = strings.TrimSpace(string(out)) == "1"
	}
	if _, err := d.run(ctx, t, "set password", d.setPasswordSQL(name, password, native)); err != nil {
		return err
	}
	// Best effort: the new password is set, losing it over a failed KILL
	// would be worse than an old session staying open.
	d.killSessions(ctx, t, name)
	return nil
}

// killSessions ends the open sessions of a user, one statement per session:
// a session ending meanwhile makes its KILL fail without stopping the others.
func (d dialect) killSessions(ctx context.Context, t services.Target, name string) error {
	out, err := d.run(ctx, t, "sessions", sessionsSQL(name))
	if err != nil {
		return err
	}
	kills, err := killSQL(out)
	if err != nil {
		return err
	}
	for _, stmt := range strings.SplitAfter(kills, "\n") {
		if stmt == "" {
			continue
		}
		_, _ = d.run(ctx, t, "kill", stmt) // an already closed session is fine
	}
	return nil
}
