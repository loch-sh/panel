// Package mosquitto is the Eclipse Mosquitto (MQTT broker) engine of the
// services module: dedicated instances, one broker per resource, with the
// tenant as its only user. The configuration and the password file are the
// panel's; the panel runs nothing inside the container.
package mosquitto

import (
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/sha512"
	"encoding/base64"
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"strings"

	"host-panel-api/internal/registry"
	"host-panel-api/internal/services"
)

// Engine runs the official eclipse-mosquitto image as its own user.
type Engine struct{}

// New returns the Mosquitto engine.
func New() *Engine { return &Engine{} }

const (
	uid = 1883 // the image user
	gid = 1883

	confFile   = "mosquitto.conf"
	confTarget = "/etc/loch/mosquitto.conf"
	// The listener lives in its own file (included), so that TLS replaces
	// it whatever the options of the main file.
	listenerFile    = "listener.conf"
	listenerTLSFile = "listener-tls.conf"
	listenerDir     = "/etc/loch/listener.d"
	passwdFile      = "passwd"

	// PBKDF2-SHA512 iterations of the password file (mosquitto_passwd's
	// default): the passwords are 190-bit random strings, out of reach of
	// an offline search; a low count keeps connections cheap.
	iterations = 101
)

func (*Engine) ID() string                        { return "mosquitto" }
func (*Engine) Kind() services.Kind               { return services.KindQueue }
func (*Engine) DefaultPort() int                  { return 1883 }
func (*Engine) Lifecycle() services.Lifecycle     { return services.Dedicated }
func (*Engine) DataOwner() (int, int)             { return uid, gid }
func (*Engine) Provisioner() services.Provisioner { return nil }

func (e *Engine) Catalog() []services.Version {
	return []services.Version{e.VersionOf("2.0", "2.0.22")}
}

// Releases: exact tags; not listed on endoflife.date.
func (*Engine) Releases() services.Releases {
	return services.Releases{Source: "docker.io/library/eclipse-mosquitto",
		Tag: regexp.MustCompile(`\A([0-9]+\.[0-9]+)\.([0-9]+)\z`), Min: "2.0"}
}

func (*Engine) VersionOf(version, tag string) services.Version {
	return services.Version{Version: version, Image: registry.Hub("eclipse-mosquitto:" + tag), DataMount: "/mosquitto/data"}
}

const (
	optMemory      = "memory"       // container memory (MB)
	optPersistence = "persistence"  // retained messages and sessions on disk
	optMessageSize = "message-size" // largest message (MB)
	optQueued      = "queued"       // messages kept per offline/slow client
)

func (*Engine) Options() []services.Option {
	return []services.Option{
		{Key: optMemory, Values: []string{"64", "128", "256", "512"}, Default: "128", Mutable: true,
			Custom: &services.CustomRange{Min: 64, Max: 4096, Step: 64}},
		{Key: optPersistence, Values: []string{"on", "off"}, Default: "on", Mutable: true},
		{Key: optMessageSize, Values: []string{"1", "10", "100"}, Default: "1", Mutable: true},
		{Key: optQueued, Values: []string{"1000", "10000", "100000"}, Default: "1000", Mutable: true},
	}
}

func (*Engine) ValidateName(string) *services.Error { return nil }

func (*Engine) Service(ref services.InstanceRef, _ services.Version, opts services.Options) services.ServiceSpec {
	mem, _ := strconv.Atoi(opts[optMemory])
	return services.ServiceSpec{
		Command: []string{"/usr/sbin/mosquitto", "-c", confTarget},
		// No secret: the port answers (the broker refuses anonymous clients).
		Healthcheck:     []string{"CMD", "nc", "-z", "127.0.0.1", "1883"},
		StopGracePeriod: "30s",
		PidsLimit:       64,
		// Declared by the image, unused (logs go to stdout).
		Tmpfs: []string{"/mosquitto/log:size=1m"},
		Files: []services.GeneratedFile{
			{Name: confFile, Target: confTarget, Content: config(mem, opts)},
			{Name: listenerFile, Target: listenerDir + "/" + listenerFile, Content: listener(false)},
		},
		User:          strconv.Itoa(uid) + ":" + strconv.Itoa(gid),
		MemLimit:      int64(mem) << 20,
		CPUs:          1,
		NoAdminSecret: true,
		State:         true,
		// The password file is refused world-readable by Mosquitto.
		SecretState: true,
		Hardened:    true,
	}
}

// listener renders the only listener, plain or requiring TLS.
func listener(tls bool) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by Loch.sh Panel (services).")
	// IPv4 only: the services network is IPv4, and a dual-stack bind fails
	// in the container ("Address in use").
	w("listener 1883 0.0.0.0")
	// A listener setting: it must follow the "listener" line in the same
	// file (elsewhere, it would open a second, default listener).
	w("max_connections 1024")
	if tls {
		w("certfile %s/%s", services.TLSMount, services.CertFile)
		w("keyfile %s/%s", services.TLSMount, services.KeyFile)
		w("tls_version tlsv1.2")
	}
	return []byte(b.String())
}

// config renders the broker configuration: no anonymous access, bounded
// clients and messages, logs on stdout; the listener is included.
func config(mem int, opts services.Options) []byte {
	size, _ := strconv.Atoi(opts[optMessageSize])
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by Loch.sh Panel (services). Rewritten by the panel: do not edit.")
	w("per_listener_settings false")
	w("allow_anonymous false")
	w("password_file %s/%s", services.StateMount, passwdFile)
	w("max_packet_size %d", size<<20)
	w("max_inflight_messages 20")
	w("max_queued_messages %s", opts[optQueued])
	// Bounded below the container limit: the broker refuses messages
	// instead of being killed.
	w("memory_limit %d", int64(mem)<<20*3/4)
	w("persistence %t", opts[optPersistence] == "on")
	w("persistence_location /mosquitto/data/")
	w("log_dest stdout")
	w("log_type error")
	w("log_type warning")
	w("log_type notice")
	w("include_dir %s", listenerDir)
	return []byte(b.String())
}

// PasswordDigest is the PBKDF2-SHA512 entry of the password file
// ("$7$<iterations>$<salt>$<hash>", as mosquitto_passwd writes it).
func (*Engine) PasswordDigest(password string) (string, error) {
	if !services.IsGeneratedPassword(password) {
		return "", fmt.Errorf("mosquitto: refusing a password not generated by the panel")
	}
	salt := make([]byte, 12)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	hash, err := pbkdf2.Key(sha512.New, password, salt, iterations, 64)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("$7$%d$%s$%s", iterations, base64.StdEncoding.EncodeToString(salt), base64.StdEncoding.EncodeToString(hash)), nil
}

var digestRe = regexp.MustCompile(`\A\$7\$[0-9]{1,7}\$[A-Za-z0-9+/]{16}\$[A-Za-z0-9+/]{86}==\z`)

// StateFiles: the password file, the tenant as its only user.
func (*Engine) StateFiles(ref services.InstanceRef, _ services.Version, _ services.Options, digest string) ([]services.GeneratedFile, error) {
	// Read back from disk: only the form the panel writes is rendered.
	if !digestRe.MatchString(digest) {
		return nil, fmt.Errorf("mosquitto: invalid password digest")
	}
	return []services.GeneratedFile{{Name: passwdFile, Content: []byte(ref.Name + ":" + digest + "\n")}}, nil
}

// TLS: required on the MQTT port (plain clients refused).
func (*Engine) TLS(services.InstanceRef, services.Version) (services.TLSSpec, bool) {
	return services.TLSSpec{Files: []services.GeneratedFile{
		{Name: listenerTLSFile, Target: listenerDir + "/" + listenerFile, Content: listener(true)},
	}}, true
}

func (*Engine) ConnectionInfo(p services.ConnParams) []services.Credential {
	scheme := "mqtt"
	if p.TLS {
		scheme = "mqtts"
	}
	uri := url.URL{Scheme: scheme, User: url.UserPassword(p.Name, p.Password), Host: p.Host + ":" + strconv.Itoa(p.Port)}
	return []services.Credential{
		{Key: "host", Value: p.Host},
		{Key: "port", Value: strconv.Itoa(p.Port)},
		{Key: "user", Value: p.Name},
		{Key: "password", Value: p.Password, Secret: true},
		{Key: "uri", Value: uri.String(), Secret: true},
	}
}
