// Engine runs the official postgres images (Debian variant: uid 999).
type Engine struct{}

// New returns the PostgreSQL engine.
func New() *Engine { return &Engine{} }

func (*Engine) ID() string                        { return "postgres" }
func (*Engine) Kind() services.Kind               { return services.KindDatabase }
func (*Engine) DefaultPort() int                  { return 5432 }
func (*Engine) Lifecycle() services.Lifecycle     { return services.OnDemand }
func (*Engine) DataOwner() (int, int)             { return 999, 999 }
func (*Engine) Provisioner() services.Provisioner { return provisioner{} }

// Catalog is the built-in catalog, with the end of support
// (https://www.postgresql.org/support/versioning/).
func (e *Engine) Catalog() []services.Version {
	v := func(version, until string) services.Version {
		out := e.VersionOf(version, version)
		out.SupportUntil = until
		return out
	}
	return []services.Version{v("18", "2030-11-14"), v("17", "2029-11-08"), v("16", "2028-11-09"), v("15", "2027-11-11")}
}

// Releases: one tag per major ("17"; its minors are new digests).
func (*Engine) Releases() services.Releases {
	return services.Releases{Source: "docker.io/library/postgres", Tag: regexp.MustCompile(`\A([0-9]+)\z`),
		LineTag: "%s", EOL: "postgresql", Min: "15"}
}

// VersionOf: PostgreSQL 18 changed the data layout: the volume is mounted one
// level up (PGDATA is /var/lib/postgresql/18/docker).
func (*Engine) VersionOf(version, tag string) services.Version {
	mount := "/var/lib/postgresql/data"
	if services.CompareVersions(version, "18") >= 0 {
		mount = "/var/lib/postgresql"
	}
	return services.Version{Version: version, Image: registry.Hub("postgres:" + tag), DataMount: mount}
}

const hbaFile = "pg_hba.conf"

// hbaContent: local socket trusted (admin commands run inside the container),
// the superuser refused over the network, every other user with a password.
// The "md5" method authenticates with SCRAM-SHA-256 every user whose
// password is stored as SCRAM (the default), and with md5 only the users
// created with the legacy mechanism.
const hbaContent = `# Generated by Loch.sh Panel (services).
local all all trust
host all postgres all reject
host all all all md5
`

func (*Engine) Service(ref services.InstanceRef, v services.Version, _ services.Options) services.ServiceSpec {
	return services.ServiceSpec{
		Command: []string{
			"postgres",
			"-c", "hba_file=/etc/loch/" + hbaFile,
			// Failed statements are not logged with their text.
			"-c", "log_min_error_statement=panic",
			"-c", "password_encryption=scram-sha-256",
			"-c", "authentication_timeout=10s",
			"-c", "max_connections=" + maxConnections,
		},
		Environment: map[string]string{
			"POSTGRES_USER":          "postgres",
			"POSTGRES_PASSWORD_FILE": services.AdminSecretMount,
			"POSTGRES_INITDB_ARGS":   "--auth-host=scram-sha-256",
		},
		Healthcheck: []string{"CMD", "pg_isready", "-U", "postgres", "-h", "127.0.0.1"},
		ShmSize:     "256m",
		Files:       []services.GeneratedFile{{Name: hbaFile, Target: "/etc/loch/" + hbaFile, Content: []byte(hbaContent)}},
	}
}

const hbaTLSFile = "pg_hba-tls.conf"

// hbaTLSContent replaces hbaContent when TLS is required: every network
// connection, the sites' included, must use TLS (hostssl).
const hbaTLSContent = `# Generated by Loch.sh Panel (services): TLS required.
local all all trust
host all postgres all reject
hostssl all all all md5
`

// TLS requires TLS on every network connection.
func (*Engine) TLS(services.InstanceRef, services.Version) (services.TLSSpec, bool) {
	return services.TLSSpec{
		Args: []string{
			"-c", "ssl=on",
			"-c", "ssl_cert_file=" + services.TLSMount + "/" + services.CertFile,
			"-c", "ssl_key_file=" + services.TLSMount + "/" + services.KeyFile,
		},
		Files: []services.GeneratedFile{{Name: hbaTLSFile, Target: "/etc/loch/" + hbaFile, Content: []byte(hbaTLSContent)}},
	}, true
}

// TLSOptional offers TLS without requiring it (SERVICES_ALLOW_TLS_OPTIONAL, chosen per exposure): the
// usual pg_hba.conf ("host" lines accept both), clients choose with
// sslmode.
func (*Engine) TLSOptional(services.InstanceRef, services.Version) (services.TLSSpec, bool) {
	return services.TLSSpec{Args: []string{
		"-c", "ssl=on",
		"-c", "ssl_cert_file=" + services.TLSMount + "/" + services.CertFile,
		"-c", "ssl_key_file=" + services.TLSMount + "/" + services.KeyFile,
	}}, true
}

func (*Engine) ConnectionInfo(p services.ConnParams) []services.Credential {
	host, port, name, password := p.Host, p.Port, p.Name, p.Password
	uri := url.URL{
		Scheme: "postgresql",
		User:   url.UserPassword(name, password),
		Host:   host + ":" + strconv.Itoa(port),
		Path:   "/" + name,
	}
	if p.TLS {
		uri.RawQuery = "sslmode=require"
	}
	return []services.Credential{
		{Key: "host", Value: host},
		{Key: "port", Value: strconv.Itoa(port)},
		{Key: "database", Value: name},
		{Key: "user", Value: name},
		{Key: "password", Value: password, Secret: true},
		{Key: "uri", Value: uri.String(), Secret: true},
	}
}

type provisioner struct{}

// reserved are the PostgreSQL system names (roles, databases, schemas).
var reserved = services.ReservedNames(
	[]string{"postgres", "template0", "template1", "public", "information_schema", "repl", "replicator", "current_user", "session_user"},
	[]string{"pg_"},
)

// ValidateName refuses the PostgreSQL system names.
func (provisioner) ValidateName(v services.Version, name string) *services.Error {
	if len(name) > v.NameLimit() {
		return services.NameTooLong(v.NameLimit())
	}
	return reserved(name)
}

func (provisioner) Init(ctx context.Context, t services.Target) error {
	_, err := run(ctx, t, "init", initSQL)
	return err
}

func (provisioner) List(ctx context.Context, t services.Target) ([]services.Resource, error) {
	out, err := run(ctx, t, "list", listSQL)
	if err != nil {
		return nil, err
	}
	return parseList(out)
}

// md5Verifier is what PostgreSQL stores for an md5 password: "md5" and the
// MD5 of the password followed by the role name.
func md5Verifier(password, name string) (string, error) {
	if !services.IsGeneratedPassword(password) {
		return "", errors.New("postgres: refusing a password that was not generated by the panel")
	}
	sum := md5.Sum([]byte(password + name))
	return "md5" + hex.EncodeToString(sum[:]), nil
}

func verifierFor(password string) (string, error) {
	if !services.IsGeneratedPassword(password) {
		return "", errors.New("postgres: refusing a password that was not generated by the panel")
	}
	return scramVerifier(password)
}

// Provision creates the role, then the database. The two steps run as
// separate commands so that a failure of the second one is known to come
// after the role was created by this call: only then is the role dropped
// again (an existing role with the same name is never touched).
func (p provisioner) Provision(ctx context.Context, t services.Target, name, password string) error {
	verifier, err := verifierFor(password)
	if err != nil {
		return err
	}
	return p.provision(ctx, t, name, verifier)
}

// LegacyAuth: md5 passwords, for clients without SCRAM-SHA-256 (deprecated
// by PostgreSQL 18, still supported).
func (provisioner) LegacyAuth(services.Version) bool { return true }

// ProvisionLegacy creates the role with an md5 password.
func (p provisioner) ProvisionLegacy(ctx context.Context, t services.Target, name, password string) error {
	verifier, err := md5Verifier(password, name)
	if err != nil {
		return err
	}
	return p.provision(ctx, t, name, verifier)
}

func (provisioner) provision(ctx context.Context, t services.Target, name, verifier string) error {
	if _, err := run(ctx, t, "create role", createRoleSQL(name, verifier)); err != nil {
		return err
	}
	_, err := run(ctx, t, "create database", createDatabaseSQL(name))
	if errors.Is(err, services.ErrOutcomeUnknown) {
		// The database may or may not exist: finishing it (restrict, open)
		// is tried once, which also tells whether it exists. Anything still
		// unknown is reported; the leftover role is listed and deletable.
		if _, ferr := run(context.WithoutCancel(ctx), t, "open database", openDatabaseSQL(name)); ferr == nil {
			return nil
		}
		return err
	}
	if err != nil {
		if _, derr := run(context.WithoutCancel(ctx), t, "drop role", dropRoleSQL(name)); derr != nil {
			return fmt.Errorf("%w (and dropping the new role failed: %v)", err, derr)
		}
		return err
	}
	return nil
}

func (provisioner) Deprovision(ctx context.Context, t services.Target, name string) error {
	_, err := run(ctx, t, "drop", dropSQL(name))
	return err
}

func (provisioner) SetPassword(ctx context.Context, t services.Target, name, password string) error {
	// The role keeps its mechanism (legacy md5 or SCRAM).
	out, err := run(ctx, t, "auth method", md5RoleSQL(name))
	if err != nil {
		return err
	}
	var verifier string
	if strings.TrimSpace(string(out)) == "t" {
		verifier, err = md5Verifier(password, name)
	} else {
		verifier, err = verifierFor(password)
	}
	if err != nil {
		return err
	}
	_, err = run(ctx, t, "set password", setPasswordSQL(name, verifier))
	return err
}
