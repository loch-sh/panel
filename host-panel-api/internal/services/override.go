// OverrideFile holds what the panel derives from the API configuration
// (published port, TLS). docker compose loads it with compose.yaml; it is
// rewritten by the panel, so closing a port works even when compose.yaml was
// edited by hand.
const OverrideFile = "compose.override.yaml"

const overrideHeader = `# Generated by Loch.sh Panel (services): published port and TLS chosen in
# the panel (within SERVICES_EXPOSE_ALLOWED_CIDRS and SERVICES_TLS).
# Rewritten by the panel: do not edit.
`

const pubNetworkKey = "pub"

// AppliedExposure is recorded in the override (x-loch): it is what the
// running container is expected to match.
type AppliedExposure struct {
	Address string `yaml:"address,omitempty"`
	Port    int    `yaml:"port,omitempty"`
	TLS     bool   `yaml:"tls,omitempty"`
	// TLSOptional: TLS offered, not required.
	TLSOptional bool `yaml:"tlsOptional,omitempty"`
}

// exposure returns the parsed published address, if any.
func (a AppliedExposure) exposure() (*Exposure, bool) {
	if a.Port == 0 {
		return nil, true
	}
	addr, err := netip.ParseAddr(a.Address)
	if err != nil || a.Port < minExposedPort || a.Port > maxExposedPort {
		return nil, false
	}
	return &Exposure{Address: addr, Port: a.Port, TLSOptional: a.TLSOptional}, true
}

type overrideFile struct {
	XLoch    AppliedExposure            `yaml:"x-loch"`
	Services map[string]overrideService `yaml:"services"`
	Networks map[string]struct{}        `yaml:"networks,omitempty"`
}

type overrideService struct {
	Command  []string                  `yaml:"command,omitempty"`
	Ports    []overridePort            `yaml:"ports,omitempty"`
	Volumes  []composeVolume           `yaml:"volumes,omitempty"`
	Networks map[string]serviceNetwork `yaml:"networks,omitempty"`
}

type overridePort struct {
	Target    int    `yaml:"target"`
	Published string `yaml:"published"`
	HostIP    string `yaml:"host_ip"`
	Protocol  string `yaml:"protocol"`
}

// effectiveSpec is the configuration the container must have: the engine
// service with the TLS settings applied.
type effectiveSpec struct {
	command []string
	files   map[string]string // target -> file name in the instance directory
	tls     bool
}

func effective(e Engine, ref InstanceRef, v Version, opts Options, tls, optional bool) effectiveSpec {
	spec := e.Service(ref, v, opts)
	eff := effectiveSpec{command: slices.Clone(spec.Command), files: map[string]string{}}
	for _, f := range spec.Files {
		eff.files[f.Target] = f.Name
	}
	if tls && supportsTLS(e, ref, v) {
		ts := tlsSpec(e, ref, v, optional)
		eff.command = append(eff.command, ts.Args...)
		for _, f := range ts.Files {
			eff.files[f.Target] = f.Name
		}
		eff.tls = true
	}
	return eff
}

// tlsFiles returns the extra generated files of an instance in TLS mode.
func tlsFiles(e Engine, ref InstanceRef, v Version, tls, optional bool) []GeneratedFile {
	if !tls {
		return nil
	}
	return tlsSpec(e, ref, v, optional).Files
}

// RenderOverride generates the override of an instance (deterministic).
// Publishing a port needs a non-internal network: the instance joins its own
// "pub" network, shared with nothing else.
func RenderOverride(e Engine, ref InstanceRef, v Version, opts Options, exp *Exposure, tls bool) ([]byte, error) {
	doc := overrideFile{Services: map[string]overrideService{serviceName: {}}}
	if exp != nil {
		svc := overrideService{
			Ports: []overridePort{{Target: e.DefaultPort(), Published: strconv.Itoa(exp.Port), HostIP: exp.HostIP(), Protocol: "tcp"}},
			Networks: map[string]serviceNetwork{
				// Merged by compose with the networks of compose.yaml.
				pubNetworkKey: {Aliases: []string{ref.Project()}},
			},
		}
		doc.XLoch = AppliedExposure{Address: exp.HostIP(), Port: exp.Port}
		doc.Networks = map[string]struct{}{pubNetworkKey: {}}
		if tls {
			eff := effective(e, ref, v, opts, true, exp.TLSOptional)
			svc.Command = eff.command
			svc.Volumes = append(svc.Volumes, composeVolume{Type: "bind", Source: "./" + CertsDir, Target: TLSMount, ReadOnly: true})
			for _, f := range tlsFiles(e, ref, v, true, exp.TLSOptional) {
				svc.Volumes = append(svc.Volumes, composeVolume{Type: "bind", Source: "./" + f.Name, Target: f.Target, ReadOnly: true})
			}
			doc.XLoch.TLS = true
			doc.XLoch.TLSOptional = exp.TLSOptional
		}
		doc.Services[serviceName] = svc
	}
	var buf bytes.Buffer
	buf.WriteString(overrideHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// parseOverride reads the applied exposure of an override.
func parseOverride(data []byte) (AppliedExposure, bool) {
	var doc overrideFile
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return AppliedExposure{}, false
	}
	return doc.XLoch, true
}

// expectedMounts are the bind mounts of the container: target -> source.
func expectedMounts(inst *instance, dataPath string, eff effectiveSpec, cfg RenderConfig) map[string]string {
	spec := inst.engine.Service(inst.ref, inst.version, inst.opts)
	want := map[string]string{inst.version.DataMount: dataPath}
	if !spec.NoAdminSecret {
		want[AdminSecretMount] = filepath.Join(inst.dir, SecretsDir, AdminSecretFile)
	}
	if spec.State {
		want[StateMount] = cfg.StatePath(inst.ref)
	}
	for target, name := range eff.files {
		want[target] = filepath.Join(inst.dir, name)
	}
	if eff.tls {
		want[TLSMount] = filepath.Join(inst.dir, CertsDir)
	}
	return want
}
