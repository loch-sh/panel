// Package elasticmq is the ElasticMQ (Amazon SQS-compatible message queue)
// engine of the services module: dedicated instances, one server per
// resource.
//
// ElasticMQ has no authentication: it accepts any credentials. Every site
// connected to the services network can use, purge or delete the queues of
// every instance. The engine is marked Unauthenticated (warning shown,
// no password); per-site private networks are planned.
package elasticmq

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"host-panel-api/internal/registry"
	"host-panel-api/internal/services"
)

// Engine runs the ElasticMQ native image (GraalVM, no JVM) unprivileged.
type Engine struct{}

// New returns the ElasticMQ engine.
func New() *Engine { return &Engine{} }

const (
	// The image runs as root: the panel runs it as its own user.
	uid = 10002
	gid = 10002

	port       = 9324
	confFile   = "elasticmq.conf"
	confTarget = "/opt/elasticmq.conf"
	// Region and account in the queue URLs (clients may use any region).
	Region    = "us-east-1"
	accountID = "000000000000"
)

func (*Engine) ID() string                        { return "elasticmq" }
func (*Engine) Kind() services.Kind               { return services.KindQueue }
func (*Engine) DefaultPort() int                  { return port }
func (*Engine) Lifecycle() services.Lifecycle     { return services.Dedicated }
func (*Engine) DataOwner() (int, int)             { return uid, gid }
func (*Engine) Provisioner() services.Provisioner { return nil }
func (*Engine) Unauthenticated() bool             { return true }

func (e *Engine) Catalog() []services.Version {
	return []services.Version{e.VersionOf("1.7", "1.7.1")}
}

// Releases: exact tags (no floating x.y tag is published); not listed on
// endoflife.date.
func (*Engine) Releases() services.Releases {
	return services.Releases{Source: "docker.io/softwaremill/elasticmq-native",
		Tag: regexp.MustCompile(`\A([0-9]+\.[0-9]+)\.([0-9]+)\z`), Min: "1.7"}
}

func (*Engine) VersionOf(version, tag string) services.Version {
	return services.Version{Version: version, Image: registry.Hub("softwaremill/elasticmq-native:" + tag), DataMount: "/data"}
}

const (
	optMemory = "memory" // container memory (MB)
	optLimits = "limits" // SQS limits: strict (as AWS) or relaxed
)

func (*Engine) Options() []services.Option {
	return []services.Option{
		{Key: optMemory, Values: []string{"128", "256", "512", "1024"}, Default: "256", Mutable: true,
			Custom: &services.CustomRange{Min: 128, Max: 8192, Step: 128}},
		{Key: optLimits, Values: []string{"strict", "relaxed"}, Default: "strict", Mutable: true},
	}
}

func (*Engine) ValidateName(string) *services.Error { return nil }

func (*Engine) Service(ref services.InstanceRef, _ services.Version, opts services.Options) services.ServiceSpec {
	mem, _ := strconv.Atoi(opts[optMemory])
	return services.ServiceSpec{
		// The image entrypoint (tini, then the server) reads confTarget.
		Healthcheck:     []string{"CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:9324/?Action=ListQueues"},
		StopGracePeriod: "30s",
		PidsLimit:       128,
		Tmpfs:           []string{"/tmp:size=16m"},
		Files:           []services.GeneratedFile{{Name: confFile, Target: confTarget, Content: config(ref, opts[optLimits])}},
		User:            strconv.Itoa(uid) + ":" + strconv.Itoa(gid),
		MemLimit:        int64(mem) << 20,
		CPUs:            1,
		NoAdminSecret:   true,
		// No credentials, but the private record is kept like every
		// dedicated instance (empty state).
		State:    true,
		Hardened: true,
	}
}

// config renders the server configuration: SQS API only (no statistics
// endpoint), queues and messages persisted in the data directory.
func config(ref services.InstanceRef, limits string) []byte {
	if limits != "relaxed" {
		limits = "strict"
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by Loch.sh Panel (services). Rewritten by the panel: do not edit.")
	w(`include classpath("application.conf")`)
	w(`node-address { protocol = http, host = %q, port = %d, context-path = "" }`, ref.Project(), port)
	w("generate-node-address = false")
	w(`rest-sqs { enabled = true, bind-port = %d, bind-hostname = "0.0.0.0", sqs-limits = %s }`, port, limits)
	w("rest-stats { enabled = false }")
	w(`queues-storage { enabled = true, path = "/data/queues.conf" }`)
	w(`messages-storage { enabled = true, uri = "jdbc:h2:/data/elasticmq" }`)
	w(`aws { region = %s, accountId = %q }`, Region, accountID)
	return []byte(b.String())
}

// PasswordDigest: no credentials; the generated password is never used.
func (*Engine) PasswordDigest(password string) (string, error) {
	if !services.IsGeneratedPassword(password) {
		return "", fmt.Errorf("elasticmq: refusing a password not generated by the panel")
	}
	return "unused", nil
}

// StateFiles: none (no authentication).
func (*Engine) StateFiles(services.InstanceRef, services.Version, services.Options, string) ([]services.GeneratedFile, error) {
	return nil, nil
}

// ConnectionInfo: the endpoint and the queue URL prefix. Any credentials
// are accepted (SDKs require some: e.g. "x").
func (*Engine) ConnectionInfo(p services.ConnParams) []services.Credential {
	endpoint := "http://" + p.Host + ":" + strconv.Itoa(p.Port)
	return []services.Credential{
		{Key: "endpoint", Value: endpoint},
		{Key: "host", Value: p.Host},
		{Key: "port", Value: strconv.Itoa(p.Port)},
		{Key: "region", Value: Region},
		{Key: "queueUrlPrefix", Value: endpoint + "/" + accountID + "/"},
	}
}
