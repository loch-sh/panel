// Package nats is the NATS engine of the services module: dedicated
// instances (one server per resource) with JetStream. The configuration is
// the panel's: the image's default one opens monitoring to the network and
// declares a cluster with hard-coded credentials.
package nats

import (
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"strings"

	"golang.org/x/crypto/bcrypt"

	"host-panel-api/internal/registry"
	"host-panel-api/internal/services"
)

// Engine runs the official nats alpine images as an unprivileged user.
type Engine struct{}

// New returns the NATS engine.
func New() *Engine { return &Engine{} }

const (
	uid = 1000
	gid = 1000
	// bcryptCost: passwords are 32 random characters (about 190 bits), out
	// of reach of an offline search at any cost; a low cost keeps the
	// pre-authentication CPU work small (a neighbour may open connections).
	bcryptCost = 8
)

func (*Engine) ID() string                        { return "nats" }
func (*Engine) Kind() services.Kind               { return services.KindMessaging }
func (*Engine) DefaultPort() int                  { return 4222 }
func (*Engine) Lifecycle() services.Lifecycle     { return services.Dedicated }
func (*Engine) DataOwner() (int, int)             { return uid, gid }
func (*Engine) Provisioner() services.Provisioner { return nil }

// Catalog is the built-in catalog (before the first discovery).
func (e *Engine) Catalog() []services.Version {
	return []services.Version{e.VersionOf("2.12", "2.12-alpine"), e.VersionOf("2.11", "2.11-alpine"), e.VersionOf("2.10", "2.10-alpine")}
}

// Releases: NATS is not listed on endoflife.date (published = supported).
func (*Engine) Releases() services.Releases {
	return services.Releases{Source: "docker.io/library/nats", Tag: regexp.MustCompile(`\A([0-9]+\.[0-9]+)-alpine\z`),
		LineTag: "%s-alpine", Min: "2.10"}
}

func (*Engine) VersionOf(version, tag string) services.Version {
	return services.Version{Version: version, Image: registry.Hub("nats:" + tag), DataMount: "/data"}
}

const (
	optMemory  = "memory"  // container memory (MB); JetStream memory store is a quarter of it
	optStorage = "storage" // JetStream file store (MB)
	optPayload = "payload" // largest message (MB)
)

func (*Engine) Options() []services.Option {
	return []services.Option{
		{Key: optMemory, Values: []string{"128", "256", "512", "1024"}, Default: "256", Mutable: true,
			Custom: &services.CustomRange{Min: 128, Max: 16384, Step: 128}},
		{Key: optStorage, Values: []string{"1024", "5120", "10240", "51200"}, Default: "1024", Mutable: true,
			Custom: &services.CustomRange{Min: 1024, Max: 1048576, Step: 1024}},
		// NATS advises small messages; larger ones cost memory per client.
		{Key: optPayload, Values: []string{"1", "8", "64"}, Default: "1", Mutable: true},
	}
}

func (*Engine) ValidateName(string) *services.Error { return nil }

const (
	confFile   = "nats.conf"
	confTarget = "/etc/loch/nats.conf"
	authFile   = "auth.conf"
)

func (*Engine) Service(ref services.InstanceRef, _ services.Version, opts services.Options) services.ServiceSpec {
	mem, _ := strconv.Atoi(opts[optMemory])
	storage, _ := strconv.Atoi(opts[optStorage])
	return services.ServiceSpec{
		Command:         []string{"nats-server", "-c", confTarget},
		Healthcheck:     []string{"CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8222/healthz"},
		StopGracePeriod: "30s",
		PidsLimit:       128,
		Files:           []services.GeneratedFile{{Name: confFile, Target: confTarget, Content: config(ref, mem, storage, opts[optPayload])}},
		User:            strconv.Itoa(uid) + ":" + strconv.Itoa(gid),
		MemLimit:        int64(mem) << 20,
		CPUs:            1,
		NoAdminSecret:   true,
		State:           true,
		Hardened:        true,
	}
}

// config renders the server configuration: one account holding the tenant
// user, with JetStream bounded; no cluster, gateway, leafnode or system
// user; monitoring on the loopback only (healthcheck).
func config(ref services.InstanceRef, mem, storage int, payload string) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by Loch.sh Panel (services). Rewritten by the panel: do not edit.")
	w("server_name: %q", ref.Project())
	w("port: 4222")
	w("http: \"127.0.0.1:8222\"")
	w("max_connections: 1024")
	w("max_subscriptions: 10000")
	w("max_payload: %sMB", payload)
	w("max_pending: 64MB")
	w("max_control_line: 4KB")
	w("write_deadline: \"5s\"")
	w("ping_interval: \"30s\"")
	w("authorization { timeout: 2 }")
	w("jetstream {")
	w("  store_dir: \"/data\"")
	w("  max_memory_store: %dMB", mem/4)
	w("  max_file_store: %dMB", storage)
	w("}")
	// Relative to this file: the state directory is mounted next to it.
	w("include \"state/%s\"", authFile)
	return []byte(b.String())
}

// StateFiles: the account and its user, with a bcrypt digest of the
// password. The account bounds JetStream (streams, consumers, storage).
func (e *Engine) StateFiles(ref services.InstanceRef, _ services.Version, opts services.Options, digest string) ([]services.GeneratedFile, error) {
	if !bcryptRe.MatchString(digest) {
		return nil, fmt.Errorf("nats: invalid password digest")
	}
	mem, _ := strconv.Atoi(opts[optMemory])
	storage, _ := strconv.Atoi(opts[optStorage])
	content := fmt.Sprintf(`# Generated by Loch.sh Panel (services).
accounts {
  APP {
    users: [ { user: %q, password: %q } ]
    jetstream: { max_mem: %dMB, max_file: %dMB, max_streams: 100, max_consumers: 1000 }
  }
}
`, ref.Name, digest, mem/4, storage)
	return []services.GeneratedFile{{Name: authFile, Content: []byte(content)}}, nil
}

// PasswordDigest is the bcrypt digest NATS expects.
func (*Engine) PasswordDigest(password string) (string, error) {
	if !services.IsGeneratedPassword(password) {
		return "", fmt.Errorf("nats: refusing a password not generated by the panel")
	}
	hash, err := bcrypt.GenerateFromPassword([]byte(password), bcryptCost)
	return string(hash), err
}

var bcryptRe = regexp.MustCompile(`\A\$2[abxy]\$[0-9]{2}\$[./A-Za-z0-9]{53}\z`)

// TLS: required on the client port (plain clients refused).
func (*Engine) TLS(services.InstanceRef, services.Version) (services.TLSSpec, bool) {
	return services.TLSSpec{Args: []string{
		"--tls",
		"--tlscert", services.TLSMount + "/" + services.CertFile,
		"--tlskey", services.TLSMount + "/" + services.KeyFile,
	}}, true
}

func (*Engine) ConnectionInfo(p services.ConnParams) []services.Credential {
	scheme := "nats"
	if p.TLS {
		scheme = "tls"
	}
	uri := url.URL{Scheme: scheme, User: url.UserPassword(p.Name, p.Password), Host: p.Host + ":" + strconv.Itoa(p.Port)}
	return []services.Credential{
		{Key: "host", Value: p.Host},
		{Key: "port", Value: strconv.Itoa(p.Port)},
		{Key: "user", Value: p.Name},
		{Key: "password", Value: p.Password, Secret: true},
		{Key: "uri", Value: uri.String(), Secret: true},
	}
}
