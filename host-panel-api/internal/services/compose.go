// Files of an instance directory.
const (
	ComposeFile      = "compose.yaml"
	SecretsDir       = "secrets"
	AdminSecretFile  = "admin_password" // also the compose secret name
	AdminSecretMount = "/run/secrets/" + AdminSecretFile
	// StateDir holds the panel-written state of a dedicated instance
	// (password digests), mounted read-only at StateMount. It lives in the
	// panel's private directory (PrivateDir), never in the stacks directory
	// (writable by CI): whoever writes the digests chooses the password. A
	// directory is mounted, not files: replacing a file atomically is seen
	// by the container at its next start.
	StateDir   = "state"
	StateMount = "/etc/loch/state"
	// PrivateDir, in the data directory, holds what the panel trusts about
	// dedicated instances: their reference (engine, version, name, options)
	// and their state.
	PrivateDir    = ".loch"
	referenceFile = "instance.json"
	serviceName   = "svc" // neutral: also used by non-database engines
)

// Labels set on every instance container.
const (
	LabelService  = "sh.loch.service"
	LabelInstance = "sh.loch.instance"
)

// Defaults of the rendered service.
const (
	defaultPidsLimit       = 512
	defaultStopGracePeriod = "60s" // databases flush on SIGTERM; compose's 10s may cut it short
	healthInterval         = "5s"
	healthTimeout          = "5s"
	healthRetries          = 30
	healthStartPeriod      = "60s"
)

// composeHeader documents how to boot the instance without the panel: its
// networks are plain Docker networks, created once per host.
func composeHeader(nets []networks.Ref) string {
	var b strings.Builder
	b.WriteString("# Generated by Loch.sh Panel (services). Boot without the panel with:\n")
	b.WriteString(networks.BootComments(nets))
	b.WriteString("#   docker compose up -d\n")
	b.WriteString("# Data lives outside this directory; deleting it does not delete the data.\n")
	return b.String()
}

// Manifest is the x-loch section of an instance compose file. Name and
// Options are set for dedicated instances (validated on load).
type Manifest struct {
	Version       int     `yaml:"version"`
	Kind          Kind    `yaml:"kind"`
	Engine        string  `yaml:"engine"`
	EngineVersion string  `yaml:"engineVersion"`
	Name          string  `yaml:"name,omitempty"`
	Options       Options `yaml:"options,omitempty"`
}

// NetworkResolver gives the Docker networks of the panel (internal/networks).
type NetworkResolver = networks.Resolver

// RenderConfig holds the installation-wide settings used to render instances.
type RenderConfig struct {
	DataDir  string // absolute, identical on the host and in the API container
	Networks NetworkResolver
}

// resolveNetworks returns the references of the networks of an instance,
// sorted. An instance always has at least one network: without one, compose
// would attach it to a default network with outbound access.
func (c RenderConfig) resolveNetworks(names []string) ([]networks.Ref, error) {
	if len(names) == 0 {
		return nil, errors.New("an instance needs at least one network")
	}
	if c.Networks == nil {
		return nil, errors.New("no network registry")
	}
	sorted := slices.Sorted(slices.Values(names))
	out := make([]networks.Ref, 0, len(sorted))
	for i, name := range sorted {
		if i > 0 && sorted[i-1] == name {
			return nil, fmt.Errorf("network %q listed twice", name)
		}
		ref, ok := c.Networks.Lookup(name)
		if !ok {
			return nil, fmt.Errorf("unknown network %q", name)
		}
		out = append(out, ref)
	}
	return out, nil
}

// DataPath is the data directory of an instance (computed, never read back).
func (c RenderConfig) DataPath(ref InstanceRef) string {
	return filepath.Join(c.DataDir, ref.Project())
}

// PrivatePath is the private directory of a dedicated instance.
func (c RenderConfig) PrivatePath(ref InstanceRef) string {
	return filepath.Join(c.DataDir, PrivateDir, ref.Project())
}

// StatePath is the state directory of a dedicated instance.
func (c RenderConfig) StatePath(ref InstanceRef) string {
	return filepath.Join(c.PrivatePath(ref), StateDir)
}

type composeFile struct {
	Name     string                    `yaml:"name"`
	XLoch    Manifest                  `yaml:"x-loch"`
	Services map[string]composeService `yaml:"services"`
	Secrets  map[string]composeSecret  `yaml:"secrets,omitempty"`
	Networks map[string]composeNetwork `yaml:"networks"`
}

type composeService struct {
	Image           string                    `yaml:"image"`
	Platform        string                    `yaml:"platform,omitempty"`
	ContainerName   string                    `yaml:"container_name"`
	Restart         string                    `yaml:"restart"`
	User            string                    `yaml:"user,omitempty"`
	Command         []string                  `yaml:"command,omitempty"`
	Environment     map[string]string         `yaml:"environment,omitempty"`
	Secrets         []string                  `yaml:"secrets,omitempty"`
	Volumes         []composeVolume           `yaml:"volumes"`
	Networks        map[string]serviceNetwork `yaml:"networks"`
	Healthcheck     composeHealthcheck        `yaml:"healthcheck"`
	StopGracePeriod string                    `yaml:"stop_grace_period"`
	Tmpfs           []string                  `yaml:"tmpfs,omitempty"`
	ShmSize         string                    `yaml:"shm_size,omitempty"`
	PidsLimit       int                       `yaml:"pids_limit"`
	MemLimit        int64                     `yaml:"mem_limit,omitempty"`
	MemswapLimit    int64                     `yaml:"memswap_limit,omitempty"` // = mem_limit: no swap beyond the limit
	CPUs            float64                   `yaml:"cpus,omitempty"`
	SecurityOpt     []string                  `yaml:"security_opt"`
	CapDrop         []string                  `yaml:"cap_drop,omitempty"`
	ReadOnly        bool                      `yaml:"read_only,omitempty"`
	Logging         composeLogging            `yaml:"logging"`
	Labels          map[string]string         `yaml:"labels"`
}

type composeVolume struct {
	Type     string `yaml:"type"`
	Source   string `yaml:"source"`
	Target   string `yaml:"target"`
	ReadOnly bool   `yaml:"read_only,omitempty"`
	Bind     struct {
		CreateHostPath bool `yaml:"create_host_path"`
	} `yaml:"bind"`
}

type serviceNetwork struct {
	Aliases []string `yaml:"aliases"`
}

type composeHealthcheck struct {
	Test        []string `yaml:"test"`
	Interval    string   `yaml:"interval"`
	Timeout     string   `yaml:"timeout"`
	Retries     int      `yaml:"retries"`
	StartPeriod string   `yaml:"start_period"`
}

type composeLogging struct {
	Driver  string            `yaml:"driver"`
	Options map[string]string `yaml:"options"`
}

type composeSecret struct {
	File string `yaml:"file"`
}

type composeNetwork struct {
	Name     string `yaml:"name"`
	External bool   `yaml:"external"`
}

// Render generates the compose file of an instance. The output is
// deterministic: re-rendering and comparing bytes detects manual edits.
func Render(e Engine, ref InstanceRef, v Version, opts Options, nets []string, cfg RenderConfig) ([]byte, error) {
	refs, err := cfg.resolveNetworks(nets)
	if err != nil {
		return nil, err
	}
	spec := e.Service(ref, v, opts)
	volumes := []composeVolume{{Type: "bind", Source: cfg.DataPath(ref), Target: v.DataMount}}
	if spec.State {
		volumes = append(volumes, composeVolume{Type: "bind", Source: cfg.StatePath(ref), Target: StateMount, ReadOnly: true})
	}
	for _, f := range spec.Files {
		// Relative source: resolved against the project directory.
		volumes = append(volumes, composeVolume{Type: "bind", Source: "./" + f.Name, Target: f.Target, ReadOnly: true})
	}
	pids := spec.PidsLimit
	if pids == 0 {
		pids = defaultPidsLimit
	}
	grace := spec.StopGracePeriod
	if grace == "" {
		grace = defaultStopGracePeriod
	}
	var secrets []string
	var secretFiles map[string]composeSecret
	if !spec.NoAdminSecret {
		secrets = []string{AdminSecretFile}
		secretFiles = map[string]composeSecret{AdminSecretFile: {File: "./" + SecretsDir + "/" + AdminSecretFile}}
	}
	service := composeService{
		Image:         v.Reference(),
		Platform:      v.Platform,
		ContainerName: ref.Project(),
		Restart:       "unless-stopped",
		User:          spec.User,
		Command:       spec.Command,
		Environment:   spec.Environment,
		Secrets:       secrets,
		Volumes:       volumes,
		Networks:      map[string]serviceNetwork{},
		Healthcheck: composeHealthcheck{
			Test: spec.Healthcheck, Interval: healthInterval, Timeout: healthTimeout,
			Retries: healthRetries, StartPeriod: healthStartPeriod,
		},
		StopGracePeriod: grace,
		Tmpfs:           spec.Tmpfs,
		ShmSize:         spec.ShmSize,
		PidsLimit:       pids,
		MemLimit:        spec.MemLimit,
		MemswapLimit:    spec.MemLimit,
		CPUs:            spec.CPUs,
		SecurityOpt:     []string{"no-new-privileges:true"},
		CapDrop:         capDrop(spec),
		ReadOnly:        spec.Hardened,
		Logging: composeLogging{
			Driver:  "json-file",
			Options: map[string]string{"max-size": "10m", "max-file": "3"},
		},
		Labels: map[string]string{
			LabelService:     e.ID(),
			LabelInstance:    ref.Key(),
			"traefik.enable": "false",
		},
	}
	doc := composeFile{
		Name: ref.Project(),
		XLoch: Manifest{
			Version: ManifestVersion, Kind: e.Kind(), Engine: e.ID(), EngineVersion: v.Version,
			Name: ref.Name, Options: opts,
		},
		Services: map[string]composeService{serviceName: service},
		Secrets:  secretFiles,
		Networks: map[string]composeNetwork{},
	}
	for _, n := range refs {
		service.Networks[n.Name] = serviceNetwork{Aliases: []string{ref.Project()}}
		doc.Networks[n.Name] = composeNetwork{Name: n.DockerName, External: true}
	}
	doc.Services[serviceName] = service
	var buf bytes.Buffer
	buf.WriteString(composeHeader(refs))
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// ParseManifest extracts the x-loch section and the project name of a
// compose file (nil when absent).
func ParseManifest(data []byte) (*Manifest, string, error) {
	var doc struct {
		Name  string    `yaml:"name"`
		XLoch *Manifest `yaml:"x-loch"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, "", err
	}
	return doc.XLoch, doc.Name, nil
}

func capDrop(spec ServiceSpec) []string {
	if spec.Hardened {
		return []string{"ALL"}
	}
	return nil
}
