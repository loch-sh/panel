// Package rabbitmq is the RabbitMQ engine of the services module: one shared
// instance per version (RabbitMQ is heavy: about 180 MB idle), one vhost
// per resource with a user of the same name that may only use its vhost.
//
// Hardening: no plugin (the image enables Prometheus, unauthenticated);
// the Erlang distribution and epmd listen on the loopback only; no guest
// user, no default vhost, no anonymous login; per-vhost and per-user limits
// and an operator policy (that tenants cannot override) bound what a tenant
// may take from the shared node.
package rabbitmq

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"time"

	"host-panel-api/internal/docker"
	"host-panel-api/internal/registry"
	"host-panel-api/internal/services"
)

// Engine runs the official rabbitmq images (Ubuntu, uid 999).
type Engine struct{}

// New returns the RabbitMQ engine.
func New() *Engine { return &Engine{} }

const (
	uid = 999
	gid = 999
	// memLimit bounds the shared node; RabbitMQ reads the cgroup limit and
	// blocks publishers at the watermark (half of it).
	memLimit = 1 << 30
)

func (*Engine) ID() string                        { return "rabbitmq" }
func (*Engine) Kind() services.Kind               { return services.KindMessaging }
func (*Engine) DefaultPort() int                  { return 5672 }
func (*Engine) Lifecycle() services.Lifecycle     { return services.OnDemand }
func (*Engine) DataOwner() (int, int)             { return uid, gid }
func (*Engine) Provisioner() services.Provisioner { return provisioner{} }

// Catalog: only the latest minor of RabbitMQ gets community support.
func (e *Engine) Catalog() []services.Version {
	return []services.Version{e.VersionOf("4.2", "4.2"), e.VersionOf("4.1", "4.1"), e.VersionOf("4.0", "4.0")}
}

// Releases: the configuration is written for RabbitMQ 4 (no classic queue
// mirroring, Khepri-ready definitions).
func (*Engine) Releases() services.Releases {
	return services.Releases{Source: "docker.io/library/rabbitmq", Tag: regexp.MustCompile(`\A([0-9]+\.[0-9]+)\z`),
		LineTag: "%s", EOL: "rabbitmq", Min: "4.0"}
}

func (*Engine) VersionOf(version, tag string) services.Version {
	return services.Version{Version: version, Image: registry.Hub("rabbitmq:" + tag), DataMount: "/var/lib/rabbitmq"}
}

const (
	confFile        = "rabbitmq.conf"
	confTLSFile     = "rabbitmq-tls.conf"
	confTarget      = "/etc/rabbitmq/rabbitmq.conf"
	pluginsFile     = "enabled_plugins"
	pluginsTarget   = "/etc/rabbitmq/enabled_plugins"
	definitionsFile = "definitions.json"
	definitionsPath = "/etc/loch/definitions.json"
	managedMark     = "loch-managed"
	execUser        = "rabbitmq"
	execTimeout     = 30 * time.Second
)

// baseConfig is shared by the plain and the TLS configurations.
const baseConfig = `# Generated by Loch.sh Panel (services). Rewritten by the panel: do not edit.
# Empty definitions: no guest user, no default vhost at the first boot.
load_definitions = ` + definitionsPath + `
auth_mechanisms.1 = PLAIN
anonymous_login_user = none
loopback_users.guest = true
log.console = true
log.console.level = warning
log.file = false
vm_memory_high_watermark.relative = 0.5
disk_free_limit.absolute = 1GB
max_message_size = 4194304
channel_max = 128
connection_max = 2048
handshake_timeout = 10000
default_queue_type = classic
`

const plainConfig = baseConfig + "listeners.tcp.default = 5672\n"

// tlsConfig: TLS only, on the same port.
const tlsConfig = baseConfig + `listeners.tcp = none
listeners.ssl.default = 5672
ssl_options.certfile = ` + services.TLSMount + "/" + services.CertFile + `
ssl_options.keyfile = ` + services.TLSMount + "/" + services.KeyFile + `
ssl_options.versions.1 = tlsv1.3
ssl_options.versions.2 = tlsv1.2
ssl_options.verify = verify_none
ssl_options.fail_if_no_peer_cert = false
ssl_handshake_timeout = 5000
`

const definitions = `{"users": [], "vhosts": [], "permissions": [], "topic_permissions": [], "parameters": [], "global_parameters": [], "policies": [], "queues": [], "exchanges": [], "bindings": []}
`

// loopbackDist keeps the Erlang distribution on the loopback.
const loopbackDist = "-kernel inet_dist_use_interface {127,0,0,1}"

func (*Engine) Service(services.InstanceRef, services.Version, services.Options) services.ServiceSpec {
	return services.ServiceSpec{
		Environment: map[string]string{
			"RABBITMQ_NODENAME":                   "rabbit@localhost",
			"ERL_EPMD_ADDRESS":                    "127.0.0.1",
			"RABBITMQ_SERVER_ADDITIONAL_ERL_ARGS": loopbackDist,
			"RABBITMQ_CTL_ERL_ARGS":               loopbackDist,
		},
		// The listener accepts connections once the node is booted (plain
		// or TLS alike).
		Healthcheck:     []string{"CMD", "bash", "-c", "exec 3<>/dev/tcp/127.0.0.1/5672"},
		StopGracePeriod: "60s",
		Files: []services.GeneratedFile{
			{Name: confFile, Target: confTarget, Content: []byte(plainConfig)},
			{Name: pluginsFile, Target: pluginsTarget, Content: []byte("[].\n")},
			{Name: definitionsFile, Target: definitionsPath, Content: []byte(definitions)},
		},
		User:          strconv.Itoa(uid) + ":" + strconv.Itoa(gid),
		MemLimit:      memLimit,
		CPUs:          2,
		NoAdminSecret: true, // administered with rabbitmqctl (Erlang cookie, local only)
	}
}

func (*Engine) TLS(services.InstanceRef, services.Version) (services.TLSSpec, bool) {
	return services.TLSSpec{Files: []services.GeneratedFile{{Name: confTLSFile, Target: confTarget, Content: []byte(tlsConfig)}}}, true
}

func (*Engine) ConnectionInfo(p services.ConnParams) []services.Credential {
	scheme := "amqp"
	if p.TLS {
		scheme = "amqps"
	}
	uri := url.URL{Scheme: scheme, User: url.UserPassword(p.Name, p.Password), Host: p.Host + ":" + strconv.Itoa(p.Port), Path: "/" + p.Name}
	return []services.Credential{
		{Key: "host", Value: p.Host},
		{Key: "port", Value: strconv.Itoa(p.Port)},
		{Key: "vhost", Value: p.Name},
		{Key: "user", Value: p.Name},
		{Key: "password", Value: p.Password, Secret: true},
		{Key: "uri", Value: uri.String(), Secret: true},
	}
}

// Limits of a resource.
const (
	// A tenant may hold at most 128 queues of 64 MB each: the shared node's
	// memory and disk alarms (which block every publisher) stay out of reach
	// of a single tenant on a sized node. Tenants cannot override an
	// operator policy.
	vhostLimits    = `{"max-connections": 256, "max-queues": 128}`
	userLimits     = `{"max-connections": 256, "max-channels": 128}`
	operatorPolicy = `{"max-length-bytes": 67108864, "overflow": "reject-publish"}`
)

type provisioner struct{}

var validateName = services.ReservedNames([]string{"guest"}, []string{"amq"})

func (provisioner) ValidateName(_ services.Version, name string) *services.Error {
	return validateName(name)
}

// ctl runs rabbitmqctl with fixed arguments (names are validated
// identifiers, never interpreted by a shell). stdin carries a password.
func ctl(ctx context.Context, t services.Target, op string, stdin []byte, args ...string) ([]byte, int, error) {
	cmd := append([]string{"timeout", "-s", "KILL", "25", "rabbitmqctl"}, args...)
	res, err := t.Exec(ctx, docker.ExecRequest{Cmd: cmd, User: execUser, Stdin: stdin, Timeout: execTimeout})
	if errors.Is(err, docker.ErrExecTimeout) || errors.Is(err, docker.ErrExecStillRunning) {
		return nil, 0, fmt.Errorf("rabbitmq %s: %w", op, services.ErrOutcomeUnknown)
	}
	if err != nil {
		return nil, 0, &services.EngineError{Op: op, Detail: "exec: " + err.Error()}
	}
	if res.ExitCode == 137 {
		return nil, 0, fmt.Errorf("rabbitmq %s: %w", op, services.ErrOutcomeUnknown)
	}
	if res.Truncated {
		return nil, 0, &services.EngineError{Op: op, Detail: "output truncated"}
	}
	return res.Stdout, res.ExitCode, nil
}

// must runs a command that has to succeed.
func must(ctx context.Context, t services.Target, op string, stdin []byte, args ...string) ([]byte, error) {
	out, code, err := ctl(ctx, t, op, stdin, args...)
	if err != nil {
		return nil, err
	}
	if code != 0 {
		return nil, &services.EngineError{Op: op, Detail: "exit code " + strconv.Itoa(code)}
	}
	return out, nil
}

// passwordInput: rabbitmqctl reads the password on stdin when it is not an
// argument (never on the command line, visible in the process list). The
// quiet flag must not be set: with it, rabbitmqctl waits forever.
func passwordInput(password string) ([]byte, error) {
	if !services.IsGeneratedPassword(password) {
		return nil, errors.New("rabbitmq: refusing a password not generated by the panel")
	}
	return []byte(password), nil
}

// Init removes what a first boot of an older configuration could have
// created (guest, the default vhost). Idempotent.
func (provisioner) Init(ctx context.Context, t services.Target) error {
	if _, err := must(ctx, t, "init", nil, "-q", "delete_user", "guest"); err != nil {
		return err
	}
	vhosts, _, err := catalog(ctx, t)
	if err != nil {
		return err
	}
	for _, v := range vhosts {
		if v.Name == "/" {
			if _, err := must(ctx, t, "init", nil, "-q", "delete_vhost", "/"); err != nil {
				return err
			}
		}
	}
	return nil
}

type listedVhost struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

type listedUser struct {
	User string   `json:"user"`
	Tags []string `json:"tags"`
}

func catalog(ctx context.Context, t services.Target) ([]listedVhost, []listedUser, error) {
	out, err := must(ctx, t, "list", nil, "-q", "list_vhosts", "name", "description", "--formatter", "json")
	if err != nil {
		return nil, nil, err
	}
	var vhosts []listedVhost
	if json.Unmarshal(out, &vhosts) != nil || vhosts == nil {
		return nil, nil, &services.EngineError{Op: "list", Detail: "unexpected output"}
	}
	out, err = must(ctx, t, "list", nil, "-q", "list_users", "--formatter", "json")
	if err != nil {
		return nil, nil, err
	}
	var users []listedUser
	if json.Unmarshal(out, &users) != nil || users == nil {
		return nil, nil, &services.EngineError{Op: "list", Detail: "unexpected output"}
	}
	return vhosts, users, nil
}

// List returns every vhost and user (the default vhost "/" included: a
// node holding it is not empty). A resource is managed when its vhost and
// its user both carry the panel mark.
func (provisioner) List(ctx context.Context, t services.Target) ([]services.Resource, error) {
	vhosts, users, err := catalog(ctx, t)
	if err != nil {
		return nil, err
	}
	markedUser := map[string]bool{}
	seen := map[string]bool{}
	var out []services.Resource
	for _, u := range users {
		for _, tag := range u.Tags {
			if tag == managedMark {
				markedUser[u.User] = true
			}
		}
	}
	for _, v := range vhosts {
		seen[v.Name] = true
		managed := v.Description == managedMark && markedUser[v.Name] && services.IsValidName(v.Name) && validateName(v.Name) == nil
		out = append(out, services.Resource{Name: v.Name, Managed: managed})
	}
	for _, u := range users {
		if !seen[u.User] {
			seen[u.User] = true
			out = append(out, services.Resource{Name: u.User})
		}
	}
	return out, nil
}

// Provision creates the vhost, then the user with permissions on it only.
// A failure half-way leaves objects that List reports: they can be deleted.
func (provisioner) Provision(ctx context.Context, t services.Target, name, password string) error {
	pw, err := passwordInput(password)
	if err != nil {
		return err
	}
	steps := []struct {
		stdin []byte
		args  []string
	}{
		{nil, []string{"-q", "add_vhost", name, "--description", managedMark, "--default-queue-type", "classic"}},
		{nil, []string{"-q", "set_vhost_limits", "-p", name, vhostLimits}},
		{nil, []string{"-q", "set_operator_policy", "-p", name, "loch-limits", ".*", operatorPolicy, "--apply-to", "queues"}},
		{pw, []string{"add_user", name}},
		{nil, []string{"-q", "set_user_tags", name, managedMark}},
		{nil, []string{"-q", "set_user_limits", name, userLimits}},
		{nil, []string{"-q", "set_permissions", "-p", name, name, ".*", ".*", ".*"}},
	}
	for _, s := range steps {
		if _, err := must(ctx, t, "provision", s.stdin, s.args...); err != nil {
			// Half created, it would not be managed (marks missing), hence
			// neither deletable nor creatable again: remove it. An unknown
			// outcome is left to List (the Manager never takes it for a
			// success).
			if !errors.Is(err, services.ErrOutcomeUnknown) {
				cctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 2*execTimeout)
				_, _, _ = ctl(cctx, t, "provision cleanup", nil, "-q", "delete_user", name)
				_, _, _ = ctl(cctx, t, "provision cleanup", nil, "-q", "delete_vhost", name)
				cancel()
			}
			return err
		}
	}
	return nil
}

// Deprovision deletes the user (its connections close), then the vhost and
// everything in it.
func (provisioner) Deprovision(ctx context.Context, t services.Target, name string) error {
	if _, err := must(ctx, t, "deprovision", nil, "-q", "delete_user", name); err != nil {
		return err
	}
	vhosts, _, err := catalog(ctx, t)
	if err != nil {
		return err
	}
	for _, v := range vhosts {
		if v.Name == name {
			_, err := must(ctx, t, "deprovision", nil, "-q", "delete_vhost", name)
			return err
		}
	}
	return nil
}

// SetPassword changes the password and closes the open connections of the
// user (they were authenticated with the old one).
func (provisioner) SetPassword(ctx context.Context, t services.Target, name, password string) error {
	pw, err := passwordInput(password)
	if err != nil {
		return err
	}
	if _, err := must(ctx, t, "set password", pw, "change_password", name); err != nil {
		return err
	}
	_, err = must(ctx, t, "set password", nil, "-q", "close_all_user_connections", name, "password changed")
	return err
}
