// ManifestVersion is the format of the x-loch section of a function
// compose file: a different version is "modified" (never executed).
const ManifestVersion = 1

// Labels set on every function container.
const (
	LabelFunction = "sh.loch.function"
	LabelManaged  = "sh.loch.managed"
)

// serviceName is the compose service of a function.
const serviceName = "fn"

// egressNetworkKey is the compose-owned, non-internal network giving
// outbound access (<project>_fn_egress), shared with nothing else. The
// underscore keeps it apart from the registry names ([a-z0-9-]).
const egressNetworkKey = "fn_egress"

// Fixed settings of the rendered service (verified as such).
const (
	pidsLimit       = 128
	shmSizeBytes    = 64 << 20
	nofileLimit     = 1024 // Lambda's; no nproc: it counts per uid on the whole host (pids_limit bounds each container)
	healthInterval  = "10s"
	healthTimeout   = "5s"
	healthRetries   = 3
	healthStart     = "30s"
	logMaxSize      = "10m"
	logMaxFile      = "3"
	defaultRegion   = "us-east-1"
	maxShutdownWait = 30 // seconds the runtime waits for a running invocation on SIGTERM
	stopMargin      = 10 // seconds between that and Docker's SIGKILL
	restartPolicy   = "unless-stopped"
	functionUser    = "10001:10001"
)

// Header of a function compose file: how to boot it without the panel.
func composeHeader(refs []networks.Ref) string {
	var b bytes.Buffer
	b.WriteString("# Generated by Loch.sh Panel (functions). Boot without the panel with:\n")
	b.WriteString(networks.BootComments(refs))
	b.WriteString("#   docker compose up -d\n")
	b.WriteString("# Code, runtime and secrets live outside this directory (FUNCTIONS_DATA_DIRECTORY).\n")
	return b.String()
}

// Manifest is the x-loch section of a function compose file.
type Manifest struct {
	Version        int    `yaml:"version"`
	Kind           string `yaml:"kind"`
	Name           string `yaml:"name"`
	Runtime        string `yaml:"runtime"`
	RuntimeVersion string `yaml:"runtimeVersion"`
	Deployment     string `yaml:"deployment"`
}

// ParseManifest extracts the x-loch section and the project name of a
// compose file (nil when absent).
func ParseManifest(data []byte) (*Manifest, string, error) {
	var doc struct {
		Name  string    `yaml:"name"`
		XLoch *Manifest `yaml:"x-loch"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, "", err
	}
	return doc.XLoch, doc.Name, nil
}

// RenderConfig holds the installation-wide settings used to render.
type RenderConfig struct {
	Paths    Paths
	Networks networks.Resolver
	// RuntimePath is the stored binary of the reference (RuntimeStore.Path).
	RuntimePath string
}

type composeFile struct {
	Name     string                    `yaml:"name"`
	XLoch    Manifest                  `yaml:"x-loch"`
	Services map[string]composeService `yaml:"services"`
	Networks map[string]composeNetwork `yaml:"networks"`
}

type composeService struct {
	Image           string                    `yaml:"image"`
	ContainerName   string                    `yaml:"container_name"`
	Restart         string                    `yaml:"restart"`
	User            string                    `yaml:"user"`
	Entrypoint      []string                  `yaml:"entrypoint"`
	Command         []string                  `yaml:"command"`
	Environment     map[string]string         `yaml:"environment"`
	EnvFile         []composeEnvFile          `yaml:"env_file"`
	Volumes         []composeVolume           `yaml:"volumes"`
	Networks        map[string]serviceNetwork `yaml:"networks"`
	Healthcheck     composeHealthcheck        `yaml:"healthcheck"`
	StopGracePeriod string                    `yaml:"stop_grace_period"`
	Tmpfs           []string                  `yaml:"tmpfs"`
	ShmSize         int64                     `yaml:"shm_size"`
	Ipc             string                    `yaml:"ipc"`
	Ulimits         map[string]composeUlimit  `yaml:"ulimits"`
	PidsLimit       int                       `yaml:"pids_limit"`
	MemLimit        int64                     `yaml:"mem_limit"`
	MemswapLimit    int64                     `yaml:"memswap_limit"` // = mem_limit: no swap
	CPUs            float64                   `yaml:"cpus"`
	SecurityOpt     []string                  `yaml:"security_opt"`
	CapDrop         []string                  `yaml:"cap_drop"`
	ReadOnly        bool                      `yaml:"read_only"`
	Logging         composeLogging            `yaml:"logging"`
	Labels          map[string]string         `yaml:"labels"`
}

type composeEnvFile struct {
	Path     string `yaml:"path"`
	Format   string `yaml:"format"`
	Required bool   `yaml:"required"`
}

type composeVolume struct {
	Type     string `yaml:"type"`
	Source   string `yaml:"source"`
	Target   string `yaml:"target"`
	ReadOnly bool   `yaml:"read_only"`
	Bind     struct {
		CreateHostPath bool   `yaml:"create_host_path"`
		Propagation    string `yaml:"propagation"`
	} `yaml:"bind"`
}

type serviceNetwork struct {
	Aliases []string `yaml:"aliases,omitempty"`
}

type composeHealthcheck struct {
	Test        []string `yaml:"test"`
	Interval    string   `yaml:"interval"`
	Timeout     string   `yaml:"timeout"`
	Retries     int      `yaml:"retries"`
	StartPeriod string   `yaml:"start_period"`
}

type composeUlimit struct {
	Soft int `yaml:"soft"`
	Hard int `yaml:"hard"`
}

type composeLogging struct {
	Driver  string            `yaml:"driver"`
	Options map[string]string `yaml:"options"`
}

type composeNetwork struct {
	Name     string `yaml:"name,omitempty"`
	External bool   `yaml:"external,omitempty"`
	Internal bool   `yaml:"internal,omitempty"`
}

// resolveNetworks returns the sorted references of a function's networks.
func resolveNetworks(names []string, r networks.Resolver) ([]networks.Ref, error) {
	if len(names) == 0 {
		// Without one, compose would attach a default network with
		// outbound access.
		return nil, errors.New("a function needs at least one network")
	}
	if r == nil {
		return nil, errors.New("no network registry")
	}
	sorted := slices.Sorted(slices.Values(names))
	out := make([]networks.Ref, 0, len(sorted))
	for i, name := range sorted {
		if i > 0 && sorted[i-1] == name {
			return nil, fmt.Errorf("network %q listed twice", name)
		}
		if name == networks.SharedName {
			return nil, errors.New("a function never joins the services network: attach it to a private network")
		}
		ref, ok := r.Lookup(name)
		if !ok {
			return nil, fmt.Errorf("unknown network %q", name)
		}
		out = append(out, ref)
	}
	return out, nil
}

// shutdownGrace is how long the runtime lets a running invocation finish on
// SIGTERM (LOCH_RUNTIME_SHUTDOWN_GRACE), shorter than stop_grace_period.
func shutdownGrace(timeout int) int { return min(timeout, maxShutdownWait) }

// renderedEnv is every variable the panel sets, values unescaped: the
// function's variables, then the panel's (which win; their names are
// reserved anyway).
func renderedEnv(ref *Reference) map[string]string {
	env := make(map[string]string, len(ref.Env)+12)
	for _, v := range ref.Env {
		env[v.Name] = v.Value
	}
	env["AWS_LAMBDA_FUNCTION_NAME"] = ref.Name
	env["AWS_LAMBDA_FUNCTION_MEMORY_SIZE"] = strconv.Itoa(ref.MemoryMB)
	env["AWS_LAMBDA_FUNCTION_TIMEOUT"] = strconv.Itoa(ref.TimeoutSeconds)
	env["AWS_REGION"] = defaultRegion
	env["AWS_EC2_METADATA_DISABLED"] = "true"
	env["PYTHONDONTWRITEBYTECODE"] = "1"
	env["LOCH_RUNTIME_SHUTDOWN_GRACE"] = strconv.Itoa(shutdownGrace(ref.TimeoutSeconds)) + "s"
	return env
}

// command is the container command: the image entrypoint and the handler,
// after "--" (the image CMD is null: the handler is always supplied).
func command(ref *Reference) []string {
	return append(append([]string{"--"}, ref.Entrypoint...), ref.Handler)
}

// renderedLabels are the labels of the function service.
func renderedLabels(n Name) map[string]string {
	return map[string]string{LabelFunction: n.String(), LabelManaged: "true", "traefik.enable": "false"}
}

// tmpfsOptions: exec allowed as on Lambda (binaries downloaded to /tmp);
// Docker's tmpfs default would be noexec.
func tmpfsOptions(ref *Reference) string {
	return "size=" + strconv.Itoa(ref.TmpSizeMB) + "m,exec,nosuid,nodev"
}

// safePathRe: the characters allowed in the paths written in a compose
// file (no "$" interpolation, no YAML or option syntax).
var safePathRe = regexp.MustCompile(`\A/[A-Za-z0-9_./-]*\z`)

// ValidDataPath reports whether a directory may be written in compose
// files (FUNCTIONS_DATA_DIRECTORY, HOSTING_STACKS_DIRECTORY).
func ValidDataPath(p string) bool { return safePathRe.MatchString(p) && filepath.Clean(p) == p }

// Render generates the compose file of a function from its validated
// reference. The output is deterministic: re-rendering and comparing bytes
// detects manual edits. A function without an active deployment cannot be
// rendered.
func Render(ref *Reference, cfg RenderConfig) ([]byte, error) {
	name, nerr := ref.FunctionName()
	if nerr != nil {
		return nil, nerr
	}
	if ref.Deployment == nil || !ValidDeploymentID(ref.Deployment.ID) {
		return nil, errors.New("the function has no valid active deployment")
	}
	if !ValidDataPath(cfg.RuntimePath) || !ValidDataPath(cfg.Paths.DataDir) || !ValidDataPath(cfg.Paths.StacksDir) {
		return nil, errors.New("invalid runtime binary or data paths")
	}
	refs, err := resolveNetworks(ref.Networks, cfg.Networks)
	if err != nil {
		return nil, err
	}
	project := name.Project()
	env := renderedEnv(ref)
	for k, v := range env {
		env[k] = composekit.EscapeInterpolation(v)
	}
	bind := func(source, target string) composeVolume {
		v := composeVolume{Type: "bind", Source: source, Target: target, ReadOnly: true}
		v.Bind.Propagation = "rprivate"
		return v
	}
	grace := shutdownGrace(ref.TimeoutSeconds)
	svc := composeService{
		Image:         ref.Image(),
		ContainerName: project,
		Restart:       restartPolicy,
		User:          functionUser,
		Entrypoint:    []string{RuntimeMount},
		Command:       command(ref),
		Environment:   env,
		// The secrets, then what the runtime checks the invoke credentials
		// with (LOCH_RUNTIME_TOKEN_SHA256, LOCH_RUNTIME_ACCESS_KEY when SigV4
		// is enabled), removed from its environment once read.
		EnvFile: []composeEnvFile{
			{Path: cfg.Paths.SecretsEnv(name), Format: "raw", Required: true},
			{Path: cfg.Paths.CredentialsEnv(name), Format: "raw", Required: true},
		},
		Volumes: []composeVolume{
			bind(cfg.RuntimePath, RuntimeMount),
			bind(cfg.Paths.Deployment(name, ref.Deployment.ID), TaskMount),
		},
		Networks: map[string]serviceNetwork{},
		Healthcheck: composeHealthcheck{
			Test:     []string{"CMD", RuntimeMount, "health"},
			Interval: healthInterval, Timeout: healthTimeout, Retries: healthRetries, StartPeriod: healthStart,
		},
		StopGracePeriod: strconv.Itoa(grace+stopMargin) + "s",
		Tmpfs:           []string{"/tmp:" + tmpfsOptions(ref)},
		ShmSize:         shmSizeBytes,
		Ipc:             "private",
		Ulimits: map[string]composeUlimit{
			"nofile": {Soft: nofileLimit, Hard: nofileLimit},
			"core":   {Soft: 0, Hard: 0},
		},
		PidsLimit:    pidsLimit,
		MemLimit:     int64(ref.MemoryMB) << 20,
		MemswapLimit: int64(ref.MemoryMB) << 20,
		CPUs:         ref.CPUs,
		SecurityOpt:  []string{"no-new-privileges:true"},
		CapDrop:      []string{"ALL"},
		ReadOnly:     true,
		Logging: composeLogging{
			Driver:  "json-file",
			Options: map[string]string{"max-size": logMaxSize, "max-file": logMaxFile},
		},
		Labels: renderedLabels(name),
	}
	doc := composeFile{
		Name: project,
		XLoch: Manifest{
			Version: ManifestVersion, Kind: "function", Name: ref.Name,
			Runtime: ref.Runtime, RuntimeVersion: ref.RuntimeVersion, Deployment: ref.Deployment.ID,
		},
		Networks: map[string]composeNetwork{},
	}
	for _, n := range refs {
		svc.Networks[n.Name] = serviceNetwork{Aliases: []string{project}}
		doc.Networks[n.Name] = composeNetwork{Name: n.DockerName, External: true}
	}
	if ref.Egress {
		svc.Networks[egressNetworkKey] = serviceNetwork{}
		doc.Networks[egressNetworkKey] = composeNetwork{}
	}
	doc.Services = map[string]composeService{serviceName: svc}
	var buf bytes.Buffer
	buf.WriteString(composeHeader(refs))
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
